///
/// # Complexity
/// O(1).
#[must_use]
pub fn otp_runner_claim_ceiling(evidence: OTPRunnerClaimEvidence) -> OTPRunnerClaimCeiling {
    let all_present = evidence.source_and_graph_evidence_present
        && evidence.unit_and_negative_fixtures_present
        && evidence.production_reachability_trace_present
        && evidence.chaos_recovery_evidence_present
        && evidence.receipt_replay_equivalence_verified;
    OTPRunnerClaimCeiling {
        otp_arazzo_runner_alive: all_present,
        workflow_process_restart_resumes: all_present,
        no_pid_semantic_identity: all_present,
    }
}

