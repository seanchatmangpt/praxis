/// Computes the L8 claim ceiling from independently-supplied evidence. The survey's
/// own text does not differentiate evidence requirements per marker (all 3 require
/// "source+graph evidence, unit+negative fixtures, a production reachability trace,
/// chaos/recovery evidence, and receipt/replay equivalence all present" together) --
/// this function does not invent an un-cited asymmetry, and requires every flag for
/// every one of the 3 markers, matching
