    /// Proves the hand-written enum is not decorative: every variant's
    /// `variant_name`/`erlang_atom` matches a real entry in the ggen-generated table,
    /// and no generated entry is left without a corresponding enum variant.
    #[test]
    fn every_variant_matches_its_generated_refusal_atom_def() {
        let variants = all_variants();
        assert_eq!(variants.len(), f16_otp_runner_vocab::REFUSAL_ATOMS.len());
        for v in &variants {
            let def = v
                .def()
                .unwrap_or_else(|| panic!("no generated def for variant {}", v.variant_name()));
            assert_eq!(def.variant_name, v.variant_name());
            assert_eq!(def.erlang_atom, v.erlang_atom());
        }
        // Every generated entry has a corresponding enum variant (surjective, not
        // just the injective direction checked above).
        for def in f16_otp_runner_vocab::REFUSAL_ATOMS {
            assert!(
                variants
                    .iter()
                    .any(|v| v.variant_name() == def.variant_name),
                "generated RefusalAtomDef {:?} has no matching OTPWorkflowRefused variant",
                def.variant_name
            );
        }
    }

