/// The F16 refusal-atom vocabulary (atlas name: `OTPWorkflowRefused`), paralleling the
/// 7 real, independently-tested Erlang refusal atoms in
/// [`f16_otp_runner_vocab::REFUSAL_ATOMS`]. See this module's own doc comment for why
/// this is new Rust vocabulary rather than a re-export (no Erlang-side unified type
/// exists to wrap), and `tests::every_variant_matches_its_generated_refusal_atom_def`
/// / `tests::refusal_atoms_appear_verbatim_in_the_real_erlang_source` for the
/// cross-checks proving each variant is a genuine parallel, not an invented one.
///
/// `context` mirrors the Erlang side's own `ContextMap` (e.g.
/// `#{stage => preactuation, workflow_id => WorkflowId, step_id => StepId}`) -- a
/// caller integrating against this vocabulary can carry the same key/value pairs a
/// real Erlang refusal would have attached, without this module inventing a narrower
/// schema than the untyped Erlang map actually has.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum OTPWorkflowRefused {
    /// Parallels Erlang `'CORRELATION_MISSING'`
    /// (`arazzo_runner_broker:dispatch/4`, stage `preactuation`).
    #[error(
        "CORRELATION_MISSING (arazzo_runner_broker:dispatch/4, stage=preactuation): {context:?}"
    )]
    CorrelationMissing { context: BTreeMap<String, String> },
    /// Parallels Erlang `'BROKER_RECEIPT_PRECONDITION_MISSING'`
    /// (`arazzo_runner_broker:check_required_prior_receipts/5`, stage `preactuation`).
    #[error(
        "BROKER_RECEIPT_PRECONDITION_MISSING (arazzo_runner_broker:check_required_prior_receipts/5, stage=preactuation): {context:?}"
    )]
    BrokerReceiptPreconditionMissing { context: BTreeMap<String, String> },
    /// Parallels Erlang `'CORRELATION_MISMATCH'`
    /// (`arazzo_runner_broker:admit_return/3`, stage `correlation`).
    #[error("CORRELATION_MISMATCH (arazzo_runner_broker:admit_return/3, stage=correlation): {context:?}")]
    CorrelationMismatch { context: BTreeMap<String, String> },
    /// Parallels Erlang `'RETURN_PROVENANCE_MISSING'`
    /// (`arazzo_runner_broker:admit_return_provenance/2`, stage `provenance`).
    #[error(
        "RETURN_PROVENANCE_MISSING (arazzo_runner_broker:admit_return_provenance/2, stage=provenance): {context:?}"
    )]
    ReturnProvenanceMissing { context: BTreeMap<String, String> },
    /// Parallels Erlang `'RETURN_AUTHORITY_REFUSED'`
    /// (`arazzo_runner_broker:admit_return_authority/2`, stage `authority`).
    #[error(
        "RETURN_AUTHORITY_REFUSED (arazzo_runner_broker:admit_return_authority/2, stage=authority): {context:?}"
    )]
    ReturnAuthorityRefused { context: BTreeMap<String, String> },
    /// Parallels Erlang `'RETURN_STRUCTURE_REFUSED'`
    /// (`arazzo_runner_broker:admit_return_structure/1`, stage `structure`).
    #[error(
        "RETURN_STRUCTURE_REFUSED (arazzo_runner_broker:admit_return_structure/1, stage=structure): {context:?}"
    )]
    ReturnStructureRefused { context: BTreeMap<String, String> },
    /// Parallels Erlang `'DIRECT_ACTUATION_REFUSED'`
    /// (`arazzo_runner_workflow:enqueue_io/2`, stage `actuation_route`).
    #[error(
        "DIRECT_ACTUATION_REFUSED (arazzo_runner_workflow:enqueue_io/2, stage=actuation_route): {context:?}"
    )]
    DirectActuationRefused { context: BTreeMap<String, String> },
}

impl OTPWorkflowRefused {
    /// Stable name matching `f16_otp_runner_vocab::RefusalAtomDef::variant_name`.
    pub const fn variant_name(&self) -> &'static str {
        match self {
            OTPWorkflowRefused::CorrelationMissing { .. } => "CorrelationMissing",
            OTPWorkflowRefused::BrokerReceiptPreconditionMissing { .. } => {
                "BrokerReceiptPreconditionMissing"
            }
            OTPWorkflowRefused::CorrelationMismatch { .. } => "CorrelationMismatch",
            OTPWorkflowRefused::ReturnProvenanceMissing { .. } => "ReturnProvenanceMissing",
            OTPWorkflowRefused::ReturnAuthorityRefused { .. } => "ReturnAuthorityRefused",
            OTPWorkflowRefused::ReturnStructureRefused { .. } => "ReturnStructureRefused",
            OTPWorkflowRefused::DirectActuationRefused { .. } => "DirectActuationRefused",
        }
    }

    /// The literal Erlang atom this variant parallels, matching
    /// `f16_otp_runner_vocab::RefusalAtomDef::erlang_atom` and (per this module's own
    /// tests) verbatim-present in the real, checked-out Erlang source.
    pub const fn erlang_atom(&self) -> &'static str {
        match self {
            OTPWorkflowRefused::CorrelationMissing { .. } => "CORRELATION_MISSING",
            OTPWorkflowRefused::BrokerReceiptPreconditionMissing { .. } => {
                "BROKER_RECEIPT_PRECONDITION_MISSING"
            }
            OTPWorkflowRefused::CorrelationMismatch { .. } => "CORRELATION_MISMATCH",
            OTPWorkflowRefused::ReturnProvenanceMissing { .. } => "RETURN_PROVENANCE_MISSING",
            OTPWorkflowRefused::ReturnAuthorityRefused { .. } => "RETURN_AUTHORITY_REFUSED",
            OTPWorkflowRefused::ReturnStructureRefused { .. } => "RETURN_STRUCTURE_REFUSED",
            OTPWorkflowRefused::DirectActuationRefused { .. } => "DIRECT_ACTUATION_REFUSED",
        }
    }

    /// The `context` map carried by this refusal, mirroring Erlang's own untyped
    /// `ContextMap`.
    pub const fn context(&self) -> &BTreeMap<String, String> {
        match self {
            OTPWorkflowRefused::CorrelationMissing { context }
            | OTPWorkflowRefused::BrokerReceiptPreconditionMissing { context }
            | OTPWorkflowRefused::CorrelationMismatch { context }
            | OTPWorkflowRefused::ReturnProvenanceMissing { context }
            | OTPWorkflowRefused::ReturnAuthorityRefused { context }
            | OTPWorkflowRefused::ReturnStructureRefused { context }
            | OTPWorkflowRefused::DirectActuationRefused { context } => context,
        }
    }

    /// This variant's full [`f16_otp_runner_vocab::RefusalAtomDef`], looked up by
    /// [`Self::variant_name`] rather than duplicated -- `None` only if the generated
    /// vocabulary table and this hand-written enum have drifted apart (a bug this
    /// module's own tests catch: `every_variant_matches_its_generated_refusal_atom_def`
    /// asserts `Some` for every variant).
    ///
    /// # Complexity
    /// O(|REFUSAL_ATOMS|) linear scan over a fixed 7-entry table -- O(1) in practice.
    pub fn def(&self) -> Option<&'static f16_otp_runner_vocab::RefusalAtomDef> {
        f16_otp_runner_vocab::REFUSAL_ATOMS
            .iter()
            .find(|d| d.variant_name == self.variant_name())
    }
}

