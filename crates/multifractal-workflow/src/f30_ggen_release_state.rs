//! Family F30 -- "GGEN Dynamic Project State and Release Admission" (atlas
//! ticket V12-030).
//!
//! Wire-phase-1 status (this pass): **MIXED, wired**. This module now
//! carries real, compiling Rust logic for the pipeline the F30 survey and
//! `v26.7.12_mermaid_atlas/families/F30_ggen-release-state.md` require:
//! `Project State RDF -> Status CONSTRUCT -> Dependency SPARQL -> Claim
//! Ceiling Query -> Mermaid Atlas Projector -> Verifier Aggregator -> Tera
//! Renderers -> Release Gate`, the 9-state lifecycle (`OBSERVATIONS_ADMITTED
//! -> STATUS_CONSTRUCTED -> DEPENDENCIES_DERIVED -> CLAIMS_BOUNDED ->
//! DIAGRAMS_PROJECTED -> VERIFIER_LIVE -> DOCS_RENDERED -> RELEASE_ADMITTED`,
//! with `REFUSED` reachable only from `STATUS_CONSTRUCTED` and
//! `DIAGRAMS_PROJECTED` per the atlas's own L5 `stateDiagram-v2`), and a
//! typed [`ReleaseAdmissionRefused`] fired at every gate. What is genuinely
//! reused/adapted/generated vs. genuinely hand-written vs. still disclosed
//! as undone is itemized per-lens below; nothing here claims more than what
//! this session verified by compiling and running the tests in this file.
//!
//! ## L1/L2 -- Project State RDF (REUSE_ADAPT, engine ALREADY_BUILT)
//!
//! [`ProjectStateGraph`] thinly wraps `ggen::graph::DeterministicGraph`
//! (`crates/ggen/src/graph.rs`, read in full this session) -- the real,
//! already-tested in-memory oxigraph store with Turtle loading, SPARQL
//! querying, and canonical-BLAKE3 `state_hash`. [`ProjectStateGraph::admit_observations`]
//! is the Project State RDF component (C1): it inserts caller-supplied
//! Turtle observation facts and fails closed
//! (`ReleaseAdmissionRefused::ObservationGraphMalformed`) on parse error --
//! no fact ever silently drops.
//!
//! ## L2 -- Status CONSTRUCT + Dependency SPARQL (HAND_WRITE_REQUIRED query text, REUSE_ADAPT mechanism)
//!
//! [`ProjectStateGraph::construct_status`] runs the real CONSTRUCT query at
//! `queries/f30-status-construct.rq` (ggen-synced from
//! `packs/f30-ggen-release-state-pack/`) via
//! `ggen::graph::GraphEngine::query`, deriving each admitted Ticket's
//! `mfwrel:derivedStatus` purely from `mfwrel:observationResult` evidence
//! (BLOCKED if any FAIL observation exists, else ALIVE if any PASS exists,
//! else UNVERIFIED) -- **never** hand-typed, which is F30's core invariant
//! and the exact defect the family survey found both `jira-tracking-pack`
//! and `post-release-pack` currently commit. [`ProjectStateGraph::derive_dependencies`]
//! runs `queries/f30-dependency-select.rq`, a direct REUSE_ADAPT of
//! `packs/jira-tracking-pack/templates/jira-deps.rq.tmpl`'s proven SPARQL
//! 1.1 `+` property-path pattern (`mfwrel:dependsOn+` in place of
//! `jira:dependsOn+`) -- only the prefix/predicate names changed.
//!
//! ## L5 -- 9-state lifecycle (HAND_WRITE_REQUIRED, new; catalog GGEN_GENERATABLE)
//!
//! [`ReleaseLifecycleState`] and [`ReleaseLifecycleState::can_transition_to`]
//! are new hand-written logic -- no existing praxis code models this exact
//! state machine. `can_transition_to` is backed by
//! [`LIFECYCLE_TRANSITIONS`] (from `f30_ggen_release_state_generated.rs`,
//! `include!`d below), a real ggen-generated projection of the atlas's own
//! L5 `stateDiagram-v2` edges (9 edges: 7 lawful chain + 2 REFUSED
//! branches), generated by `ggen sync` from
//! `packs/f30-ggen-release-state-pack/ontology.ttl`'s
//! `mfwrel:LifecycleTransition` individuals; two independent fresh runs
//! produced byte-identical output (`shasum -a 256`), confirming
//! determinism. [`lifecycle_catalog_states_match_enum`] and
//! [`lifecycle_transitions_match_atlas_edges`] below cross-check the
//! generated catalog against both the hand-written enum and the atlas
//! document text itself, so the two representations cannot silently drift
//! apart.
//!
//! ## L8 -- Claim Ceiling Query (HAND_WRITE_REQUIRED, new)
//!
//! [`bound_claim`] implements the atlas's L8 gate: five boolean evidence
//! inputs (source/graph evidence, unit+negative fixtures, production
//! reachability trace, chaos/recovery evidence, receipt/replay
//! equivalence) bound the highest [`ClaimLevel`] the pipeline may emit --
//! `Alive` only if all five hold, `Partial` if source evidence plus test
//! fixtures hold, `Unverified` otherwise (the no-overclaiming default,
//! never rounded up). This mirrors the honest-downgrade philosophy of
//! `scripts/verifier_report.py` (REAL_PASS / REAL_FAIL /
//! NOT_YET_AVAILABLE, read in full this session) without porting its
//! Python or its ticket-table-regex parsing, which is architecturally
//! unrelated to this graph-backed pipeline. [`VerifierAggregate::ceiling`]
//! extends the same bounding rule across multiple named verifier fields,
//! deterministically (fields are sorted by name before folding, so
//! `HashMap`/caller iteration order never affects the result -- repo
//! invariant #5).
//!
//! ## L6 -- Mermaid Atlas Projector + Tera Renderers (HAND_WRITE_REQUIRED projector; REUSE Tera engine)
//!
//! [`project_mermaid`] is a real, non-decorative function: it walks
//! [`LIFECYCLE_TRANSITIONS`] (the same ggen-generated table
//! `can_transition_to` consults, never a second hand-typed copy) and
//! renders a genuine `stateDiagram-v2` Mermaid document, annotating
//! whichever state the caller names as current. [`render_docs`] uses the
//! real `tera` crate (`Tera::default().render_str`, the same idiom
//! `crates/ggen/src/template.rs` uses) to interpolate already-computed
//! [`StatusFact`]/[`DependencyEdge`]/[`ClaimLevel`] values into a Markdown
//! doc template -- the template contains no conditional logic that could
//! decide status; it only prints what the CONSTRUCT/Claim-Ceiling stages
//! already computed, honoring F30's "Tera does not decide release state"
//! invariant literally.
//!
//! ## L7 -- Concurrency/Recovery/Chaos (PARTIAL, hand-written, disclosed gap)
//!
//! [`ReceiptHead`] implements the atomic idempotency + correlation gate
//! the atlas's L7 diagram requires: [`ReceiptHead::admit_or_replay`]
//! replays the prior [`ReleaseReceipt`] content hash for a duplicate event
//! (same `correlation_id`, same content hash) rather than recomputing, and
//! refuses [`ReleaseAdmissionRefused::ConcurrentDrift`] for a conflicting
//! one (same `correlation_id`, different hash). [`ReceiptHead::open`]
//! genuinely persists this as a newline-delimited JSON journal on disk
//! (`serde_json`, already a dependency) and reloads it on construction --
//! `receipt_head_survives_restart` below proves a fresh `ReceiptHead`
//! opened against the same path after the original struct is dropped
//! still recognizes a prior correlation id as a replay, which is the
//! literal "process or engine restart" scenario the atlas's L7 diagram
//! names. Disclosed gap, not glossed over: this journal is a local file,
//! not a networked/multi-writer durable store, so true multi-process
//! concurrent-writer chaos (two engines racing on the same journal file)
//! is not exercised or guaranteed safe this pass -- `std::fs::OpenOptions`
//! append is not cross-process-atomic on all platforms. A production
//! deployment would need a real lock or a transactional store; that
//! remains HAND_WRITE_REQUIRED.
//!
//! ## Release Gate (HAND_WRITE_REQUIRED, new)
//!
//! [`admit_release`] is the orchestration: it walks every lawful edge of
//! [`LIFECYCLE_TRANSITIONS`] via [`require_transition`] (never assumes the
//! linear order silently), refuses at the two atlas-declared REFUSED
//! branches (`STATUS_CONSTRUCTED` on a malformed CONSTRUCT result,
//! `DIAGRAMS_PROJECTED` on a stale caller-declared state hash), computes
//! [`ReleaseReceipt::content_hash`] as a BLAKE3 digest over a *sorted*
//! concatenation of every derived fact (repo invariant #2: sorted before
//! hashing, verified by `admit_release_end_to_end_happy_path`'s
//! byte-identical-across-two-calls assertion), and gates the final
//! admission through [`ReceiptHead`]. Disclosed scope boundary: the
//! Verifier Aggregator component this Release Gate consults
//! ([`VerifierAggregate`]) does not itself spawn `cargo test` / `just
//! verify-all` -- it consumes already-collected [`VerifierField`] results.
//! Building a live, sandboxed, command-spawning verifier is real
//! additional scope (security-sensitive: arbitrary process execution) and
//! remains HAND_WRITE_REQUIRED, named here rather than silently absent.

