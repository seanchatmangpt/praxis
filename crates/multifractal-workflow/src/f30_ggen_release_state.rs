/// F30-L5's 9-state machine, mirroring [`LIFECYCLE_STATES`] one-for-one
/// (crosschecked by `lifecycle_catalog_states_match_enum` below).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ReleaseLifecycleState {
    ObservationsAdmitted,
    StatusConstructed,
    DependenciesDerived,
    ClaimsBounded,
    DiagramsProjected,
    VerifierLive,
    DocsRendered,
    ReleaseAdmitted,
    Refused,
}

impl ReleaseLifecycleState {
    /// The exact atlas name (`LIFECYCLE_STATES[*].name`) for this state.
    pub const fn atlas_name(self) -> &'static str {
        match self {
            Self::ObservationsAdmitted => "OBSERVATIONS_ADMITTED",
            Self::StatusConstructed => "STATUS_CONSTRUCTED",
            Self::DependenciesDerived => "DEPENDENCIES_DERIVED",
            Self::ClaimsBounded => "CLAIMS_BOUNDED",
            Self::DiagramsProjected => "DIAGRAMS_PROJECTED",
            Self::VerifierLive => "VERIFIER_LIVE",
            Self::DocsRendered => "DOCS_RENDERED",
            Self::ReleaseAdmitted => "RELEASE_ADMITTED",
            Self::Refused => "REFUSED",
        }
    }

    /// Inverse of [`Self::atlas_name`]; `None` for any name not in the
    /// atlas's declared 9-state catalog.
    pub fn from_atlas_name(name: &str) -> Option<Self> {
        ALL_STATES.iter().copied().find(|s| s.atlas_name() == name)
    }

    /// Real transition check, backed by [`LIFECYCLE_TRANSITIONS`]
    /// (ggen-generated, not a second hand-typed copy of the atlas's edge
    /// list) -- so an atlas edit that adds/removes an edge is caught by
    /// regenerating the pack, not silently missed by a duplicated Rust
    /// match arm.
    pub fn can_transition_to(self, next: Self) -> bool {
        LIFECYCLE_TRANSITIONS
            .iter()
            .any(|t| t.from == self.atlas_name() && t.to == next.atlas_name())
    }
}

/// Every [`ReleaseLifecycleState`] variant, for catalog crosschecks and
/// [`ReleaseLifecycleState::from_atlas_name`]'s lookup.
const ALL_STATES: &[ReleaseLifecycleState] = &[
    ReleaseLifecycleState::ObservationsAdmitted,
    ReleaseLifecycleState::StatusConstructed,
    ReleaseLifecycleState::DependenciesDerived,
    ReleaseLifecycleState::ClaimsBounded,
    ReleaseLifecycleState::DiagramsProjected,
    ReleaseLifecycleState::VerifierLive,
    ReleaseLifecycleState::DocsRendered,
    ReleaseLifecycleState::ReleaseAdmitted,
    ReleaseLifecycleState::Refused,
];

/// Fails closed with [`ReleaseAdmissionRefused::UnauthorizedTransition`]
/// unless `from -> to` is a real edge in [`LIFECYCLE_TRANSITIONS`]. The
/// Release Gate calls this at every step of [`admit_release`] instead of
/// assuming the linear chain order.
fn require_transition(
    from: ReleaseLifecycleState,
    to: ReleaseLifecycleState,
) -> Result<(), ReleaseAdmissionRefused> {
    if from.can_transition_to(to) {
        Ok(())
    } else {
        Err(ReleaseAdmissionRefused::UnauthorizedTransition {
            from: from.atlas_name(),
            to: to.atlas_name(),
        })
    }
}

