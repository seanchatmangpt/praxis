/// One `mfwrel:Ticket`'s CONSTRUCT-derived status
/// (`mfwrel:derivedStatus`) -- never hand-typed, only ever produced by
/// [`ProjectStateGraph::construct_status`].
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct StatusFact {
    pub ticket: String,
    pub status: String,
}

/// One `(ticket, transitive dependency)` edge from the Dependency SELECT.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct DependencyEdge {
    pub ticket: String,
    pub depends_on: String,
}

/// F30-L2 component C1 (Project State RDF): a thin wrapper over
/// `ggen::graph::DeterministicGraph` carrying this family's own typed
/// refusal at every fallible boundary.
pub struct ProjectStateGraph {
    graph: DeterministicGraph,
}

impl ProjectStateGraph {
    /// Real, empty in-memory oxigraph-backed graph.
    pub fn new() -> Result<Self, ReleaseAdmissionRefused> {
        let graph = DeterministicGraph::new().map_err(|e| {
            ReleaseAdmissionRefused::ObservationGraphMalformed {
                reason: e.to_string(),
            }
        })?;
        Ok(Self { graph })
    }

    /// Admits Turtle observation facts. Fails closed on malformed Turtle --
    /// no partial/silent admission.
    pub fn admit_observations(&self, turtle: &str) -> Result<usize, ReleaseAdmissionRefused> {
        self.graph.insert_turtle(turtle).map_err(|e| {
            ReleaseAdmissionRefused::ObservationGraphMalformed {
                reason: e.to_string(),
            }
        })
    }

    /// Canonical BLAKE3 state hash of the currently-admitted facts (sorted
    /// N-Quads, `ggen::graph::DeterministicGraph::state_hash`).
    pub fn state_hash(&self) -> Result<[u8; 32], ReleaseAdmissionRefused> {
        self.graph
            .state_hash()
            .map_err(|e| ReleaseAdmissionRefused::ObservationGraphMalformed {
                reason: e.to_string(),
            })
    }

    /// F30-L2 component C2: runs the real Status CONSTRUCT query and
    /// derives each admitted Ticket's status purely as a graph consequence.
    pub fn construct_status(&self) -> Result<Vec<StatusFact>, ReleaseAdmissionRefused> {
        let results = GraphEngine::query(&self.graph, STATUS_CONSTRUCT_QUERY).map_err(|e| {
            ReleaseAdmissionRefused::StatusConstructMalformed {
                query_path: STATUS_CONSTRUCT_QUERY_PATH,
                reason: e.to_string(),
            }
        })?;
        parse_status_construct_result(results)
    }

    /// F30-L2 component C3: runs the real Dependency SELECT query
    /// (`mfwrel:dependsOn+`), returning every transitive `(ticket, dep)`
    /// pair.
    pub fn derive_dependencies(&self) -> Result<Vec<DependencyEdge>, ReleaseAdmissionRefused> {
        let results = GraphEngine::query(&self.graph, DEPENDENCY_SELECT_QUERY).map_err(|e| {
            ReleaseAdmissionRefused::DependencySelectMalformed {
                query_path: DEPENDENCY_SELECT_QUERY_PATH,
                reason: e.to_string(),
            }
        })?;
        parse_dependency_select_result(results)
    }
}

/// Extracted from [`ProjectStateGraph::construct_status`] so it is
/// unit-testable against hand-built [`EngineQueryResults`] fixtures without
/// needing a live SPARQL evaluation for the negative (wrong-shape) path.
fn parse_status_construct_result(
    results: EngineQueryResults,
) -> Result<Vec<StatusFact>, ReleaseAdmissionRefused> {
    let EngineQueryResults::Graph(triples) = results else {
        return Err(ReleaseAdmissionRefused::StatusConstructMalformed {
            query_path: STATUS_CONSTRUCT_QUERY_PATH,
            reason: "query did not evaluate to CONSTRUCT/DESCRIBE triples".to_string(),
        });
    };
    let mut facts: Vec<StatusFact> = triples
        .iter()
        .filter(|t| t.predicate.ends_with("#derivedStatus>"))
        .map(|t| StatusFact {
            ticket: local_name(&t.subject),
            status: t.object_value.clone(),
        })
        .collect();
    // Sorted before any hashing/rendering consumes this (repo invariant #2).
    facts.sort_by(|a, b| {
        (a.ticket.as_str(), a.status.as_str()).cmp(&(b.ticket.as_str(), b.status.as_str()))
    });
    Ok(facts)
}

/// Extracted from [`ProjectStateGraph::derive_dependencies`], same rationale
/// as [`parse_status_construct_result`].
fn parse_dependency_select_result(
    results: EngineQueryResults,
) -> Result<Vec<DependencyEdge>, ReleaseAdmissionRefused> {
    let EngineQueryResults::Solutions(rows) = results else {
        return Err(ReleaseAdmissionRefused::DependencySelectMalformed {
            query_path: DEPENDENCY_SELECT_QUERY_PATH,
            reason: "query did not evaluate to SELECT rows".to_string(),
        });
    };
    let mut edges: Vec<DependencyEdge> = rows
        .iter()
        .filter_map(|row| {
            let id = row.get("id")?.clone();
            let dep = row.get("dep")?.clone();
            Some(DependencyEdge {
                ticket: id,
                depends_on: dep,
            })
        })
        .collect();
    edges.sort_by(|a, b| {
        (a.ticket.as_str(), a.depends_on.as_str()).cmp(&(b.ticket.as_str(), b.depends_on.as_str()))
    });
    Ok(edges)
}

/// N-Triples subject/predicate is `<full#Iri>` or a plain literal; take the
/// fragment/last-segment as a readable label, falling back to the raw
/// (bracket-stripped) string if there is no `#`/`/` to split on.
fn local_name(ntriples_term: &str) -> String {
    let stripped = ntriples_term.trim_start_matches('<').trim_end_matches('>');
    stripped
        .rsplit(['#', '/'])
        .next()
        .unwrap_or(stripped)
        .to_string()
}

