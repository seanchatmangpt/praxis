/// F30's typed refusal taxonomy. Every variant has >=1 end-to-end test in
/// this file's `tests` module (repo invariant #1 / #8, and the F30 survey's
/// own invariant #5).
#[derive(Debug, thiserror::Error)]
pub enum ReleaseAdmissionRefused {
    /// The observation Turtle failed to parse, or the in-memory graph could
    /// not be constructed/hashed. Refused pre-`OBSERVATIONS_ADMITTED`: a
    /// malformed world never reaches the first lifecycle state at all
    /// (the same MALFORMED_WORLD_PREPLAN_REFUSAL discipline
    /// `f07_shape_admission.rs` documents for its own graph admission).
    #[error("observation graph malformed: {reason}")]
    ObservationGraphMalformed { reason: String },

    /// The Status CONSTRUCT query (`{query_path}`) either failed to
    /// evaluate or did not evaluate to CONSTRUCT/DESCRIBE triples --
    /// F30-L5's `STATUS_CONSTRUCTED -> REFUSED: invalid` branch.
    #[error("Status CONSTRUCT `{query_path}` invalid: {reason}")]
    StatusConstructMalformed {
        query_path: &'static str,
        reason: String,
    },

    /// The Dependency SELECT query (`{query_path}`) either failed to
    /// evaluate or did not evaluate to SELECT rows.
    #[error("Dependency SELECT `{query_path}` invalid: {reason}")]
    DependencySelectMalformed {
        query_path: &'static str,
        reason: String,
    },

    /// The caller declared an `expected_state_hash` that no longer matches
    /// the live graph's `state_hash()` -- a concurrent workflow admitted
    /// new observations between the caller's read and this admission
    /// attempt. F30-L5's `DIAGRAMS_PROJECTED -> REFUSED: authority or
    /// conformance failure` branch.
    #[error(
        "project state is stale: caller declared state_hash {declared}, live graph state_hash is {live}"
    )]
    StaleProjectState { declared: String, live: String },

    /// An orchestration step attempted a `from -> to` pair that is not a
    /// real edge in [`LIFECYCLE_TRANSITIONS`].
    #[error("illegal lifecycle transition: {from} -> {to} is not a lawful F30-L5 edge")]
    UnauthorizedTransition {
        from: &'static str,
        to: &'static str,
    },

    /// L7 atomic idempotency + correlation gate: `correlation_id` was
    /// already admitted with a different content hash -- concurrent-edit
    /// drift, refused rather than silently overwritten.
    #[error(
        "correlation id `{correlation_id}` already admitted with a different content hash (first {first_hash}, this attempt {this_hash})"
    )]
    ConcurrentDrift {
        correlation_id: String,
        first_hash: String,
        this_hash: String,
    },

    /// The durable receipt-head journal at `path` could not be read or
    /// written.
    #[error("receipt head journal at `{path}` unreadable/unwritable: {reason}")]
    ReceiptHeadJournalError { path: String, reason: String },

    /// A Tera render of a release doc failed. The template itself is
    /// fixed, static, and contains no state-deciding logic (F30's own
    /// invariant); this variant only fires on a genuine Tera engine error
    /// (e.g. malformed template syntax), never a "status" decision.
    #[error("release doc render failed: {reason}")]
    DocRenderFailed { reason: String },
}

