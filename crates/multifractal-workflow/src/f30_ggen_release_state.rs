/// D8 in F30-L6's data flow: the bound artifact of a successful
/// [`admit_release`] call.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReleaseReceipt {
    pub lifecycle_state: ReleaseLifecycleState,
    pub claim_level: ClaimLevel,
    /// Hex-encoded BLAKE3 digest over a sorted canonical concatenation of
    /// every derived fact (repo invariant #2).
    pub content_hash: String,
    pub mermaid: String,
    pub docs: Vec<RenderedReleaseDoc>,
}

/// BLAKE3 over a *sorted* concatenation of every fact the receipt covers
/// (repo invariant #2: sorted before hashing). `status_facts`/`dependencies`
/// are already caller-sorted by their producing functions; this sorts the
/// full assembled line-set again regardless, so the hash never depends on
/// any caller-supplied ordering either.
fn compute_receipt_hash(
    lifecycle_state: ReleaseLifecycleState,
    claim_level: ClaimLevel,
    status_facts: &[StatusFact],
    dependencies: &[DependencyEdge],
    mermaid: &str,
    docs: &[RenderedReleaseDoc],
) -> String {
    let mut lines: Vec<String> = Vec::new();
    lines.push(format!("lifecycle_state={}", lifecycle_state.atlas_name()));
    lines.push(format!("claim_level={claim_level}"));
    for f in status_facts {
        lines.push(format!("status:{}:{}", f.ticket, f.status));
    }
    for d in dependencies {
        lines.push(format!("dep:{}:{}", d.ticket, d.depends_on));
    }
    for d in docs {
        lines.push(format!("doc:{}:{}", d.name, d.content));
    }
    lines.push(format!("mermaid:{mermaid}"));
    lines.sort();
    blake3::hash(lines.join("\n").as_bytes())
        .to_hex()
        .to_string()
}

/// One JSONL entry of the L7 durable receipt-head journal.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
struct ReceiptHeadEntry {
    correlation_id: String,
    content_hash: String,
    lifecycle_state: String,
    claim_level: String,
}

/// F30-L7's "atomic idempotency and correlation gate" + "durable receipt
/// head". See module doc's L7 section for what is genuinely durable vs.
/// the disclosed multi-process-safety gap.
pub struct ReceiptHead {
    path: Option<PathBuf>,
    entries: HashMap<String, ReceiptHeadEntry>,
}

impl ReceiptHead {
    /// In-memory only -- no restart recovery. For callers/tests that don't
    /// need L7 durability.
    pub fn in_memory() -> Self {
        Self {
            path: None,
            entries: HashMap::new(),
        }
    }

    /// Real durable journal: loads existing entries from `path` if present
    /// (a prior process's receipt head genuinely survives restart),
    /// appending new entries synchronously thereafter.
    pub fn open(path: &Path) -> Result<Self, ReleaseAdmissionRefused> {
        let mut entries = HashMap::new();
        match std::fs::read_to_string(path) {
            Ok(raw) => {
                for line in raw.lines().filter(|l| !l.trim().is_empty()) {
                    let entry: ReceiptHeadEntry = serde_json::from_str(line).map_err(|e| {
                        ReleaseAdmissionRefused::ReceiptHeadJournalError {
                            path: path.display().to_string(),
                            reason: format!("malformed journal line: {e}"),
                        }
                    })?;
                    entries.insert(entry.correlation_id.clone(), entry);
                }
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => {
                return Err(ReleaseAdmissionRefused::ReceiptHeadJournalError {
                    path: path.display().to_string(),
                    reason: e.to_string(),
                });
            }
        }
        Ok(Self {
            path: Some(path.to_path_buf()),
            entries,
        })
    }

    /// The atomic idempotency + correlation gate: a duplicate event (same
    /// `correlation_id`, same `content_hash`) replays (`Ok(true)`) rather
    /// than being treated as new; a conflicting event (same
    /// `correlation_id`, different `content_hash`) is concurrent-edit
    /// drift and refuses.
    pub fn admit_or_replay(
        &mut self,
        correlation_id: &str,
        content_hash: &str,
        lifecycle_state: ReleaseLifecycleState,
        claim_level: ClaimLevel,
    ) -> Result<bool, ReleaseAdmissionRefused> {
        if let Some(prior) = self.entries.get(correlation_id) {
            if prior.content_hash == content_hash {
                return Ok(true);
            }
            return Err(ReleaseAdmissionRefused::ConcurrentDrift {
                correlation_id: correlation_id.to_string(),
                first_hash: prior.content_hash.clone(),
                this_hash: content_hash.to_string(),
            });
        }
        let entry = ReceiptHeadEntry {
            correlation_id: correlation_id.to_string(),
            content_hash: content_hash.to_string(),
            lifecycle_state: lifecycle_state.atlas_name().to_string(),
            claim_level: claim_level.to_string(),
        };
        if let Some(path) = &self.path {
            use std::io::Write as _;
            let line = serde_json::to_string(&entry).map_err(|e| {
                ReleaseAdmissionRefused::ReceiptHeadJournalError {
                    path: path.display().to_string(),
                    reason: e.to_string(),
                }
            })?;
            let mut file = std::fs::OpenOptions::new()
                .create(true)
                .append(true)
                .open(path)
                .map_err(|e| ReleaseAdmissionRefused::ReceiptHeadJournalError {
                    path: path.display().to_string(),
                    reason: e.to_string(),
                })?;
            writeln!(file, "{line}").map_err(|e| {
                ReleaseAdmissionRefused::ReceiptHeadJournalError {
                    path: path.display().to_string(),
                    reason: e.to_string(),
                }
            })?;
        }
        self.entries.insert(correlation_id.to_string(), entry);
        Ok(false)
    }
}

/// Everything [`admit_release`] needs from its caller.
pub struct ReleaseAdmissionInput<'a> {
    pub observation_turtle: &'a str,
    pub claim_evidence: ClaimEvidence,
    pub correlation_id: &'a str,
    /// If `Some`, the caller's last-known graph state hash; a mismatch
    /// against the live hash after admission refuses
    /// [`ReleaseAdmissionRefused::StaleProjectState`] (F30-L5's
    /// `DIAGRAMS_PROJECTED -> REFUSED` branch).
    pub expected_state_hash: Option<[u8; 32]>,
}

/// The Release Gate (F30-L2 component C8): walks every stage of the
/// pipeline, consulting [`require_transition`] at each lifecycle step
/// rather than assuming the linear order, and returns `(receipt,
/// is_replay)` -- `is_replay` is `true` when [`ReceiptHead::admit_or_replay`]
/// recognized this exact `(correlation_id, content_hash)` pair as a
/// duplicate event rather than a new admission.
pub fn admit_release(
    input: &ReleaseAdmissionInput<'_>,
    receipt_head: &mut ReceiptHead,
) -> Result<(ReleaseReceipt, bool), ReleaseAdmissionRefused> {
    // OBSERVATIONS_ADMITTED
    let graph = ProjectStateGraph::new()?;
    graph.admit_observations(input.observation_turtle)?;
    let live_hash = graph.state_hash()?;

    require_transition(
        ReleaseLifecycleState::ObservationsAdmitted,
        ReleaseLifecycleState::StatusConstructed,
    )?;
    // STATUS_CONSTRUCTED (may refuse: invalid)
    let status_facts = graph.construct_status()?;

    require_transition(
        ReleaseLifecycleState::StatusConstructed,
        ReleaseLifecycleState::DependenciesDerived,
    )?;
    // DEPENDENCIES_DERIVED
    let dependencies = graph.derive_dependencies()?;

    require_transition(
        ReleaseLifecycleState::DependenciesDerived,
        ReleaseLifecycleState::ClaimsBounded,
    )?;
    // CLAIMS_BOUNDED
    let claim_level = bound_claim(&input.claim_evidence);

    require_transition(
        ReleaseLifecycleState::ClaimsBounded,
        ReleaseLifecycleState::DiagramsProjected,
    )?;
    // DIAGRAMS_PROJECTED (may refuse: authority or conformance failure --
    // checked here, before the projector runs, so a stale caller-declared
    // hash never reaches it)
    if let Some(expected) = input.expected_state_hash {
        if expected != live_hash {
            return Err(ReleaseAdmissionRefused::StaleProjectState {
                declared: hex::encode(expected),
                live: hex::encode(live_hash),
            });
        }
    }
    let mermaid = project_mermaid(ReleaseLifecycleState::DiagramsProjected, None);

    require_transition(
        ReleaseLifecycleState::DiagramsProjected,
        ReleaseLifecycleState::VerifierLive,
    )?;
    // VERIFIER_LIVE -- see module doc's Release Gate section for the
    // disclosed scope boundary (no live command-spawning verifier this
    // pass; claim_level from CLAIMS_BOUNDED is the only signal folded in).

    require_transition(
        ReleaseLifecycleState::VerifierLive,
        ReleaseLifecycleState::DocsRendered,
    )?;
    // DOCS_RENDERED
    let docs = render_docs(
        ReleaseLifecycleState::ReleaseAdmitted,
        claim_level,
        &status_facts,
        &dependencies,
    )?;

    require_transition(
        ReleaseLifecycleState::DocsRendered,
        ReleaseLifecycleState::ReleaseAdmitted,
    )?;
    // RELEASE_ADMITTED, gated by the L7 atomic idempotency + correlation gate
    let content_hash = compute_receipt_hash(
        ReleaseLifecycleState::ReleaseAdmitted,
        claim_level,
        &status_facts,
        &dependencies,
        &mermaid,
        &docs,
    );
    let is_replay = receipt_head.admit_or_replay(
        input.correlation_id,
        &content_hash,
        ReleaseLifecycleState::ReleaseAdmitted,
        claim_level,
    )?;

    Ok((
        ReleaseReceipt {
            lifecycle_state: ReleaseLifecycleState::ReleaseAdmitted,
            claim_level,
            content_hash,
            mermaid,
            docs,
        },
        is_replay,
    ))
}

