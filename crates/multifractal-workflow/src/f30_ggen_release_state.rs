/// F30-L2 component C5: projects the *real* [`LIFECYCLE_TRANSITIONS`] table
/// (the same one [`ReleaseLifecycleState::can_transition_to`] consults)
/// into a genuine Mermaid `stateDiagram-v2` document, marking `current` and
/// (if present) noting the refusal that halted the pipeline there.
pub fn project_mermaid(
    current: ReleaseLifecycleState,
    refusal: Option<&ReleaseAdmissionRefused>,
) -> String {
    use std::fmt::Write as _;
    let mut out = String::from("stateDiagram-v2\n    [*] --> OBSERVATIONS_ADMITTED\n");
    for t in LIFECYCLE_TRANSITIONS {
        let _ = writeln!(out, "    {} --> {}: {}", t.from, t.to, t.label);
    }
    let _ = writeln!(out, "    RELEASE_ADMITTED --> [*]");
    let _ = writeln!(out, "    REFUSED --> [*]: typed ReleaseAdmissionRefused");
    let _ = writeln!(
        out,
        "    note right of {}: current state",
        current.atlas_name()
    );
    if let Some(r) = refusal {
        let note = r.to_string().replace(['\n', ':', '"'], " ");
        let _ = writeln!(out, "    note right of REFUSED: {note}");
    }
    out
}

