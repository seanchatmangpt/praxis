//! Family F01 -- "Standing Algebra" (atlas ticket V12-001).
//!
//! Wire-phase-1 status (this pass): **MIXED, wired**. This module now carries
//! real, compiling Rust logic for the pipeline the F01 survey required --
//! `Raw Observation -> Observation Gate -> Admission Engine -> Manufacture
//! Boundary -> Standing Algebra -> Receipt Emitter -> Replay Verifier`, the
//! 7-state lifecycle (`RAW -> OBSERVED -> ADMITTED -> MANUFACTURED ->
//! STANDING -> RECEIPTED -> REPLAYABLE`, with `REFUSED` reachable only from
//! `OBSERVED`/`MANUFACTURED`), and a `SilentPromotionRefused` typed refusal
//! fired at every gate. What is genuinely reused/adapted vs. genuinely
//! hand-written is disclosed per-lens below and in each item's own doc
//! comment; nothing here claims more than what this session verified by
//! compiling and running the tests in this file.
//!
//! ## L1/L2 -- Observation Gate + Admission Engine (REUSE_ADAPT)
//!
//! [`StandingCase::admit`] reuses `praxis_graphlaw::shacl::ValidationReport`
//! directly as the conformance-evidence type, and copies the exact
//! promotion semantics of
//! [`praxis_graphlaw::chatman::closure::RecursiveSocketClosure::promote_observed_to_admitted`]
//! (promote iff `evidence.conforms`, refuse otherwise, never on say-so) --
//! generalized from that function's `WorkflowSocketId`-keyed children to
//! this family's generic per-case admission. The real function was read in
//! full this session (`crates/praxis-graphlaw/src/chatman/closure.rs:382`).
//!
//! ## L3 -- Manufacture Boundary (REUSE_ADAPT)
//!
//! [`StandingCase::manufacture`] adapts the three-check pattern of
//! `praxis_core::arazzo::admit_manufactured_arazzo`
//! (`crates/praxis-core/src/arazzo.rs:186`, read in full this session):
//! refuse with no source digest presented, refuse on artifact/claimed-digest
//! mismatch. Written generically over `&[u8]` + a caller-declared source
//! digest instead of Arazzo-specific types, since those types are not
//! domain-agnostic -- only the semantic pattern (and its BLAKE3 recompute
//! discipline) is reused.
//!
//! ## L4 -- Standing Algebra proper (REUSE_ADAPT, minimal)
//!
//! [`StandingCase::promote_to_standing`] is `A = mu(O*)`
//! (`docs/CHATMAN_EQUATION.md`) at its most reduced form: once `manufacture`
//! has verified a real digest, granting standing is the recorded lifecycle
//! transition itself -- there is no additional evidence to consult that
//! wasn't already required to reach `Manufactured`.
//!
//! ## L6/L8 -- Receipt Emitter + Replay Verifier (REUSE_ADAPT)
//!
//! [`StandingCase::emit_receipt`] calls
//! `praxis_graphlaw::chatman::abi::Receipt::from_canonical_nquads` directly
//! (real, tested BLAKE3-over-canonical-N-Quads construction; read in full
