/// The 7-state Standing Algebra lifecycle plus the `Refused` escape state
/// (F01 survey lens L5). `Refused` is reachable only from `Observed` or
/// `Manufactured` -- see [`LifecycleState::can_transition_to`], which is
/// the literal, exhaustive encoding of that invariant (not merely a
/// comment about it).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum LifecycleState {
    Raw = 0,
    Observed = 1,
    Admitted = 2,
    Manufactured = 3,
    Standing = 4,
    Receipted = 5,
    Replayable = 6,
    Refused = 7,
}

impl LifecycleState {
    /// Whether `self -> next` is a legal Standing Algebra edge.
    ///
    /// `Observed` never satisfies terminal/admitted status on its own (it
    /// can only advance to `Admitted` or exit to `Refused`); `Refused` is
    /// reachable only from `Observed` or `Manufactured` (F01 survey L5).
    ///
    /// # Complexity
    /// O(1).
    #[must_use]
    pub fn can_transition_to(self, next: LifecycleState) -> bool {
        use LifecycleState::{
            Admitted, Manufactured, Observed, Raw, Receipted, Refused, Replayable, Standing,
        };
        matches!(
            (self, next),
            (Raw, Observed)
                | (Observed, Admitted)
                | (Observed, Refused)
                | (Admitted, Manufactured)
                | (Manufactured, Standing)
                | (Manufactured, Refused)
                | (Standing, Receipted)
                | (Receipted, Replayable)
        )
    }

    /// One-hot replay token bit for this state (F01 survey L6/L8), mirroring
    /// `crates/praxis-core/src/replay_adapter.rs`'s `TOK_START`/`TOK_JUDGED`/
    /// ... pattern, generalized from that file's fixed 3-step lifecycle to
    /// this family's 7. `Refused` deliberately has no bit: it exits the
    /// lawful pipeline rather than continuing it, so it plays no part in
    /// the standing-chain replay token flow.
    ///
    /// # Complexity
    /// O(1).
    fn token_bit(self) -> u64 {
        match self {
            LifecycleState::Raw => 1 << 0,
            LifecycleState::Observed => 1 << 1,
            LifecycleState::Admitted => 1 << 2,
            LifecycleState::Manufactured => 1 << 3,
            LifecycleState::Standing => 1 << 4,
            LifecycleState::Receipted => 1 << 5,
            LifecycleState::Replayable => 1 << 6,
            LifecycleState::Refused => 0,
        }
    }
}

/// The four gates a candidate passes on its way to standing (F01 survey L1-L4).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Gate {
    ObservationGate,
    AdmissionEngine,
    ManufactureBoundary,
    StandingAlgebra,
}

/// F01's typed refusal taxonomy. `SilentPromotionRefused` is the shared
/// escape hatch the survey requires at every gate (L1-L4); the remaining
/// variants cover the lifecycle machine (L5), concurrency/chaos (L7), and
/// replay equivalence (L6/L8) lenses. Every variant carries the concrete
/// offending context, never a bare generic message.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum Refusal {
    /// A candidate failed to clear one of the four admission gates (L1-L4).
    /// Never fired silently -- every call site that can fail this way
    /// returns this variant rather than defaulting the candidate forward.
    #[error("SilentPromotionRefused at {gate:?}: {reason}")]
    SilentPromotionRefused { gate: Gate, reason: String },
    /// An attempted lifecycle transition is not one of the legal edges in
    /// [`LifecycleState::can_transition_to`].
    #[error("illegal Standing Algebra lifecycle transition {from:?} -> {to:?}")]
    IllegalLifecycleTransition {
        from: LifecycleState,
        to: LifecycleState,
    },
    /// L7: a duplicate or stale (out-of-order / post-restart re-delivered)
    /// event was refused by the idempotency+correlation gate rather than
    /// silently re-admitted.
    #[error("duplicate or stale event refused (correlation_id={correlation_id:?}): {reason}")]
    DuplicateOrStaleEvent {
        correlation_id: String,
        reason: String,
    },
    /// L6/L8: replaying the recorded standing chain did not reconstruct an
    /// equivalent consequence to the receipted one.
    #[error(
        "replay of the receipted standing chain did not reconstruct an equivalent consequence: {reason}"
    )]
    ReplayEquivalenceFailed { reason: String },
    /// The underlying `praxis_graphlaw::chatman::abi::Receipt` construction
    /// refused (e.g. empty/unsorted canonical N-Quads material); the
    /// original refusal's message is preserved verbatim in `reason`.
    #[error("receipt emission refused: {0}")]
    ReceiptEmissionRefused(String),
}

/// One correlation-scoped raw observation entering the pipeline (L1).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RawObservation {
    pub correlation_id: String,
    pub payload: String,
}

/// One case moving through the Standing Algebra pipeline: `Raw Observation
/// -> Observation Gate -> Admission Engine -> Manufacture Boundary ->
/// Standing Algebra -> Receipt Emitter -> Replay Verifier`. Every stage is
/// an explicit, typed, potentially-refusing method; there is no path that
/// advances `state` without going through one of them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StandingCase {
    correlation_id: String,
    state: LifecycleState,
    manufactured_digest_hex: Option<String>,
    receipt: Option<Receipt>,
    transitions: Vec<(LifecycleState, LifecycleState)>,
}

impl StandingCase {
    /// Opens a new case at `Raw` for `correlation_id`.
    ///
    /// # Complexity
    /// O(1).
    #[must_use]
    pub fn new(correlation_id: impl Into<String>) -> Self {
        StandingCase {
            correlation_id: correlation_id.into(),
            state: LifecycleState::Raw,
            manufactured_digest_hex: None,
            receipt: None,
            transitions: Vec::new(),
        }
    }

    /// Current lifecycle state.
    #[must_use]
    pub fn state(&self) -> LifecycleState {
        self.state
    }

    /// The lawful transition history recorded so far, in order taken. Feeds
    /// [`replay_standing_chain`]/[`verify_receipt_head`].
    #[must_use]
    pub fn transitions(&self) -> &[(LifecycleState, LifecycleState)] {
        &self.transitions
    }

    /// The receipt this case emitted, if [`Self::emit_receipt`] has run.
    #[must_use]
    pub fn receipt(&self) -> Option<&Receipt> {
        self.receipt.as_ref()
    }

    /// Advances `state` to `next` iff it is a legal edge, recording the
    /// transition for later replay.
    ///
    /// # Complexity
    /// O(1).
    fn transition(&mut self, next: LifecycleState) -> Result<(), Refusal> {
        if !self.state.can_transition_to(next) {
            return Err(Refusal::IllegalLifecycleTransition {
                from: self.state,
                to: next,
            });
        }
        self.transitions.push((self.state, next));
        self.state = next;
        Ok(())
    }

    /// L1 Observation Gate: `Raw -> Observed`. Refuses an empty payload
    /// rather than silently observing nothing.
    ///
    /// # Errors
    /// [`Refusal::SilentPromotionRefused`] if `raw.payload` is empty, or
    /// [`Refusal::IllegalLifecycleTransition`] if this case is not `Raw`.
    ///
    /// # Complexity
    /// O(1).
    pub fn observe(&mut self, raw: &RawObservation) -> Result<(), Refusal> {
        if raw.payload.is_empty() {
            return Err(Refusal::SilentPromotionRefused {
                gate: Gate::ObservationGate,
                reason: "raw observation payload is empty; nothing to observe".to_string(),
            });
        }
        self.transition(LifecycleState::Observed)
    }

    /// L2 Admission Engine: `Observed -> Admitted`, gated on real SHACL
    /// conformance evidence. Adapted from
    /// `RecursiveSocketClosure::promote_observed_to_admitted`'s exact
    /// semantics: promotion iff `evidence.conforms`, never on say-so.
    ///
    /// # Errors
    /// [`Refusal::SilentPromotionRefused`] if `evidence.conforms` is
    /// `false` -- the case stays at `Observed` (L5: observation never
    /// self-promotes to admitted).
    ///
    /// # Complexity
    /// O(1) (the evidence is pre-computed by the caller; this only
    /// inspects `evidence.conforms`/`evidence.results.len()`).
    pub fn admit(&mut self, evidence: &ValidationReport) -> Result<(), Refusal> {
        if !evidence.conforms {
            return Err(Refusal::SilentPromotionRefused {
                gate: Gate::AdmissionEngine,
                reason: format!(
                    "SHACL conformance evidence does not conform ({} validation result(s)); \
                     observation is not promoted to admission",
                    evidence.results.len()
                ),
            });
        }
        self.transition(LifecycleState::Admitted)
    }

    /// L3 Manufacture Boundary: `Admitted -> Manufactured`. Adapted from
    /// `praxis_core::arazzo::admit_manufactured_arazzo`'s three-check
    /// pattern (no source digest presented / digest mismatch), generalized
    /// over an arbitrary artifact byte string and caller-declared source
    /// digest instead of Arazzo-specific types.
    ///
    /// # Errors
    /// [`Refusal::SilentPromotionRefused`] if `source_digest_hex` is empty
    /// (no admitted source bound), or if `artifact_bytes` does not
    /// recompute to `claimed_artifact_digest_hex` (the artifact does not
    /// match its own claimed digest).
    ///
    /// # Complexity
    /// O(b) where b = `artifact_bytes.len()` (one BLAKE3 pass).
    pub fn manufacture(
        &mut self,
        artifact_bytes: &[u8],
        source_digest_hex: &str,
        claimed_artifact_digest_hex: &str,
    ) -> Result<(), Refusal> {
        if source_digest_hex.is_empty() {
            return Err(Refusal::SilentPromotionRefused {
                gate: Gate::ManufactureBoundary,
                reason: "no source digest presented; manufacture without an admitted source \
                         is refused"
                    .to_string(),
            });
        }
        let recomputed = hex::encode(blake3::hash(artifact_bytes).as_bytes());
        if recomputed != claimed_artifact_digest_hex {
            return Err(Refusal::SilentPromotionRefused {
                gate: Gate::ManufactureBoundary,
                reason: format!(
                    "presented artifact recomputes to {recomputed}, but the claimed digest is \
                     {claimed_artifact_digest_hex}; the artifact does not attest this claim"
                ),
            });
        }
        self.manufactured_digest_hex = Some(recomputed);
        self.transition(LifecycleState::Manufactured)
    }

    /// L4 Standing Algebra proper: `Manufactured -> Standing`. This is
    /// `A = mu(O*)` at its most reduced form: once `manufacture` has
    /// verified a real digest, granting standing is the recorded lifecycle
    /// transition itself.
    ///
    /// # Errors
    /// [`Refusal::SilentPromotionRefused`] if no manufactured digest is on
    /// record (a case cannot reach `Manufactured` without passing L3, so
    /// this only fires if called out of order and `transition` itself
    /// would also refuse).
    ///
    /// # Complexity
    /// O(1).
    pub fn promote_to_standing(&mut self) -> Result<(), Refusal> {
        if self.manufactured_digest_hex.is_none() {
            return Err(Refusal::SilentPromotionRefused {
                gate: Gate::StandingAlgebra,
                reason: "no manufactured artifact digest on record; standing cannot be granted \
                         without a manufactured artifact"
                    .to_string(),
            });
        }
        self.transition(LifecycleState::Standing)
    }

    /// L6 Receipt Emitter: `Standing -> Receipted`. Reuses
    /// `Receipt::from_canonical_nquads` directly (real, tested BLAKE3-over-
    /// canonical-N-Quads construction).
    ///
    /// # Errors
    /// [`Refusal::ReceiptEmissionRefused`] if the underlying receipt
    /// construction refuses (empty/unsorted material, per
    /// `Receipt::from_canonical_nquads`'s own contract).
    ///
    /// # Complexity
    /// O(n) for the underlying sortedness check plus O(bytes) for the
    /// BLAKE3 digest, n = number of N-Quads lines.
    pub fn emit_receipt(
        &mut self,
        witness: &str,
        replay_hint: &str,
        canon_nquads: &str,
    ) -> Result<Receipt, Refusal> {
        let subject = format!("urn:multifractal-workflow:f01:{}", self.correlation_id);
        let receipt = Receipt::from_canonical_nquads(&subject, witness, replay_hint, canon_nquads)
            .map_err(|e| Refusal::ReceiptEmissionRefused(e.to_string()))?;
        self.transition(LifecycleState::Receipted)?;
        self.receipt = Some(receipt.clone());
        Ok(receipt)
    }

    /// L6/L8 Replay Verifier: `Receipted -> Replayable`. Callers should
    /// have already confirmed [`verify_receipt_head`] on
    /// [`Self::transitions`] before calling this -- this method itself only
    /// records the final lifecycle edge, it does not re-run replay.
    ///
    /// # Errors
    /// [`Refusal::IllegalLifecycleTransition`] if this case is not
    /// `Receipted`.
    ///
    /// # Complexity
    /// O(1).
    pub fn mark_replayable(&mut self) -> Result<(), Refusal> {
        self.transition(LifecycleState::Replayable)
    }

    /// Exits to `Refused` from `Observed` or `Manufactured` (the only two
    /// legal `Refused` predecessors, F01 survey L5).
    ///
    /// # Errors
    /// [`Refusal::IllegalLifecycleTransition`] from any other state.
    ///
    /// # Complexity
    /// O(1).
    pub fn refuse(&mut self) -> Result<(), Refusal> {
        self.transition(LifecycleState::Refused)
    }
}

/// L7: an atomic idempotency+correlation gate (survey: HAND_WRITE_REQUIRED,
/// no deterministic Rust analog found elsewhere in this repo). Tracks the
/// highest admitted sequence number per correlation id in a `BTreeMap`
/// (never `HashMap`, for deterministic iteration); admits an event iff its
/// sequence number is strictly newer than the last admitted one for that
/// correlation id, refusing duplicates and stale/out-of-order re-delivery
/// (including the "process/engine restart re-delivers an old event" case,
/// provided the ledger itself is consulted rather than reset -- this pass's
/// ledger is in-memory only; persisting it across a real process restart is
/// an undone follow-on, disclosed here rather than silently assumed).
#[derive(Debug, Clone, Default)]
pub struct IdempotencyLedger {
    seen: BTreeMap<String, u64>,
}

impl IdempotencyLedger {
    /// An empty ledger.
    #[must_use]
    pub fn new() -> Self {
        IdempotencyLedger::default()
    }

    /// Admits `(correlation_id, sequence)` iff it is strictly newer than any
    /// previously admitted sequence for that correlation id.
    ///
    /// # Errors
    /// [`Refusal::DuplicateOrStaleEvent`] if `sequence` is less than or
    /// equal to the last admitted sequence for `correlation_id`.
    ///
    /// # Complexity
    /// O(log n), n = distinct correlation ids seen so far.
    pub fn admit(&mut self, correlation_id: &str, sequence: u64) -> Result<(), Refusal> {
        if let Some(prev) = self.seen.get(correlation_id).copied() {
            if sequence <= prev {
                return Err(Refusal::DuplicateOrStaleEvent {
                    correlation_id: correlation_id.to_string(),
                    reason: format!(
                        "sequence {sequence} is not newer than the last admitted sequence \
                         {prev} for this correlation id"
                    ),
                });
            }
        }
        self.seen.insert(correlation_id.to_string(), sequence);
        Ok(())
    }
}

/// L6/L8: replays a recorded lawful transition history through
/// [`PowlReplayVerifier`] and returns the real conformance metrics, or the
/// first violation encountered. A lawful, in-order Standing Algebra chain
/// (`Raw -> Observed -> Admitted -> Manufactured -> Standing -> Receipted ->
/// Replayable`) replays to `fitness == 0x0001_0000` (1.0, Q16.16), matching
/// `crates/praxis-core/src/replay_adapter.rs`'s own judge/admit/receipt
/// precedent.
///
/// # Errors
/// The first [`ReplayViolation`] encountered (out-of-order or unknown-node
/// transition).
///
/// # Complexity
/// O(t) over `transitions`, t = chain length (each frame is O(1)).
pub fn replay_standing_chain(
    transitions: &[(LifecycleState, LifecycleState)],
) -> Result<ConformanceMetrics, ReplayViolation> {
    let mut verifier = PowlReplayVerifier::new(LifecycleState::Raw.token_bit());
    for (idx, (from, to)) in transitions.iter().enumerate() {
        let frame = PowlReplayFrame {
            node_id: *to as u32,
            node_bit: to.token_bit(),
            required_tokens: from.token_bit(),
            produces_tokens: to.token_bit(),
            activity: format!("{from:?}->{to:?}"),
            ts_ns: idx as u64,
            object_ids: Vec::new(),
        };
        verifier.replay_frame(&frame)?;
    }
    Ok(verifier.finalize())
}

/// L6/L8: verifies that replaying `transitions` reconstructs a consequence
/// equivalent to `receipt` -- the receipt head and the replay must agree,
/// not merely both exist. "Equivalent" means: replay is lawful (fitness ==
/// 1.0, Q16.16) *and* the receipt's own digest recomputes
/// ([`Receipt::verify`]).
///
/// # Errors
/// [`Refusal::ReplayEquivalenceFailed`] if replay is a
/// [`ReplayViolation`], if fitness is not `0x0001_0000`, or if
/// `receipt.verify()` fails.
///
/// # Complexity
/// O(t) for the replay plus O(bytes) for the receipt digest recompute.
pub fn verify_receipt_head(
    transitions: &[(LifecycleState, LifecycleState)],
    receipt: &Receipt,
) -> Result<ConformanceMetrics, Refusal> {
    let metrics = replay_standing_chain(transitions).map_err(|violation| {
        Refusal::ReplayEquivalenceFailed {
            reason: format!("{violation:?}"),
        }
    })?;
    if metrics.fitness != 0x0001_0000 {
        return Err(Refusal::ReplayEquivalenceFailed {
            reason: format!(
                "replay fitness {:#010x} is not 1.0; the standing chain does not reconstruct \
                 equivalently",
                metrics.fitness
            ),
        });
    }
    receipt
        .verify()
        .map_err(|e| Refusal::ReplayEquivalenceFailed {
            reason: e.to_string(),
        })?;
    Ok(metrics)
}

/// L8: the independently-supplied evidence flags [`claim_ceiling`] combines.
/// None of these ever defaults to `true`; every field must be set by the
/// caller from real evidence gathered elsewhere, never derived by
/// `claim_ceiling` itself.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct ClaimEvidence {
    pub source_and_graph_evidence_present: bool,
    pub unit_and_negative_fixtures_present: bool,
    pub production_reachability_trace_present: bool,
    pub chaos_recovery_evidence_present: bool,
    pub receipt_replay_equivalence_verified: bool,
}

/// L8: the only three claims this family may ever emit. New vocabulary --
/// none of these three names existed anywhere in this repo before this
/// pass (grep-confirmed by the F01 survey).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ClaimCeiling {
    pub standing_algebra_alive: bool,
    pub zero_silent_promotion: bool,
    pub replayable_standing_chain: bool,
}

/// Computes the L8 claim ceiling from independently-supplied evidence. All
/// three claims require every [`ClaimEvidence`] flag to be `true`;
/// `replayable_standing_chain` additionally re-checks
/// `receipt_replay_equivalence_verified` explicitly (redundant with the
/// combined check today, but kept as its own named condition so a future
/// loosening of the combined gate cannot silently loosen this specific
/// claim too).
///
/// # Complexity
/// O(1).
#[must_use]
pub fn claim_ceiling(evidence: ClaimEvidence) -> ClaimCeiling {
    let all_present = evidence.source_and_graph_evidence_present
        && evidence.unit_and_negative_fixtures_present
        && evidence.production_reachability_trace_present
        && evidence.chaos_recovery_evidence_present
        && evidence.receipt_replay_equivalence_verified;
    ClaimCeiling {
        standing_algebra_alive: all_present,
        zero_silent_promotion: all_present,
        replayable_standing_chain: all_present && evidence.receipt_replay_equivalence_verified,
    }
}

