// Profile Resolver (D1: ShapeProfile)
// ---------------------------------------------------------------------

/// A resolved shape profile: the SHACL shapes graph and (optionally) the
/// ShEx schema + shape map an admission attempt is checked against.
///
/// ShEx is compact-syntax (ShExC) rather than ShExJ, because ShExC is what a
/// hand-authored profile is realistically written in
/// (`shexc_parser::parse_shexc`'s own doc comment makes the same
/// observation about real-world ShEx authoring).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShapeProfile {
    /// Identifies this profile in receipts and refusals.
    pub profile_id: String,
    /// Turtle-serialized SHACL shapes graph.
    pub shacl_shapes_turtle: String,
    /// Optional ShExC schema plus the `(focus_node_iri, shape_label_iri)`
    /// pairs to check against it. `None` means ShEx is vacuously
    /// conformant for this profile (SHACL-only admission) -- see
    /// `ViolationSet::normalize`'s `shex_conforms` computation.
    pub shex: Option<(String, Vec<(String, String)>)>,
}

impl ShapeProfile {
    /// Profile Resolver stage: confirms the profile is well-formed --
    /// the SHACL shapes graph parses, and (if present) the ShExC schema
    /// parses -- before any admission attempt uses it. This is real parse
    /// validation via `praxis_graphlaw::shacl::ShapesGraph::parse` and
    /// `praxis_graphlaw::shexc_parser::parse_shexc`, not a no-op.
    ///
    /// # Complexity
    /// O(bytes of shacl_shapes_turtle + bytes of shex schema), one parse
    /// pass each; bounded by the same complexity as the underlying parsers.
    pub fn resolve(&self) -> Result<(), ShapeAdmissionRefused> {
        praxis_graphlaw::shacl::ShapesGraph::parse(&self.shacl_shapes_turtle).map_err(|e| {
            ShapeAdmissionRefused::ProfileMalformed {
                profile_id: self.profile_id.clone(),
                reason: format!("SHACL shapes graph failed to parse: {e}"),
            }
        })?;
        if let Some((schema_shexc, _map)) = &self.shex {
            praxis_graphlaw::shexc_parser::parse_shexc(schema_shexc).map_err(|e| {
                ShapeAdmissionRefused::ProfileMalformed {
                    profile_id: self.profile_id.clone(),
                    reason: format!("ShExC schema failed to parse: {e}"),
                }
            })?;
        }
        Ok(())
    }
}

// ---------------------------------------------------------------------
// Refusal taxonomy (typed, no catch-all)
// ---------------------------------------------------------------------

/// F07's typed refusal taxonomy. Every variant carries the context needed
/// to debug it; no variant is a bare "Error"/"Failed". Mirrors the pattern
/// `praxis_graphlaw::chatman::abi::Refusal` already establishes in this
/// repo (String-context enum variants via `thiserror`), adapted rather than
/// reused directly since that enum is chatman-engine-specific.
///
/// A refusal here carries no standing and grants no actuation: every
/// variant is returned from [`ShapeAdmissionGate::admit`] before any
/// [`AdmissionHandoff`] is constructed, so a caller holding a
/// `ShapeAdmissionRefused` never also holds a handoff for the same attempt.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ShapeAdmissionRefused {
    /// The supplied [`ShapeProfile`] does not parse (malformed SHACL or ShEx).
    #[error("profile `{profile_id}` malformed: {reason}")]
    ProfileMalformed { profile_id: String, reason: String },
    /// The input graph is not valid Turtle -- refused before any shape
    /// check runs, since there is no graph to check. This is the
    /// MALFORMED_WORLD_PREPLAN_REFUSAL case: a malformed world cannot
    /// become a planning state, and is refused pre-plan.
    #[error("input graph failed to parse as Turtle: {reason}")]
    GraphMalformed { reason: String },
    /// The SHACL validator itself returned an error (distinct from a
    /// non-conforming report, which is a normal [`AdmissionDecision::Refused`]
    /// outcome, not this variant).
    ///
    /// # Disclosed: structurally unreachable through [`ShapeAdmissionGate::admit`] today
    ///
    /// [`ShapeProfile::resolve`] already parses `shacl_shapes_turtle` via
    /// `praxis_graphlaw::shacl::ShapesGraph::parse` and is called with `?`
    /// before [`TripleStore::validate_shacl`] runs on the *same, unmutated*
    /// string. `ShapesGraph::parse` is a pure function of its input bytes
    /// (no I/O, no environment dependence -- confirmed by reading
    /// `shacl::model::ShapesGraph::parse`), and
    /// `praxis_graphlaw::shacl::Validator::validate` itself is infallible
    /// (`ValidationReport`, not `Result`). So `validate_shacl`'s *only*
    /// failure mode is the same parse `resolve()` already proved succeeds
    /// on the identical bytes -- there is no admit()-reachable input for
    /// which this variant is constructed. This is disclosed, not
    /// silently left untested: forcing a test through `admit()` would
    /// require fabricating a divergence between the two parses that does
    /// not exist. Precedent: `ObservationAdmissionRefused::LedgerUnavailable`
    /// in `f02_observation_admission.rs`'s test-module doc table.
    #[error("SHACL validator error for profile `{profile_id}`: {reason}")]
    ShaclValidatorError { profile_id: String, reason: String },
    /// The ShEx validator itself returned an error (same distinction as
    /// [`ShaclValidatorError`]'s doc comment draws for SHACL).
    ///
    /// Unlike `ShaclValidatorError`, this variant *is* reachable through
    /// [`ShapeAdmissionGate::admit`]: [`ShapeProfile::resolve`] only proves
    /// the ShExC schema string parses (it explicitly discards the shape
    /// map -- see `resolve`'s `let Some((schema_shexc, _map))`). It never
    /// checks that every `(focus_node, shape_label)` pair in
    /// [`ShapeProfile::shex`]'s shape map actually names a shape declared
    /// in that schema. A profile can resolve cleanly (schema is
    /// well-formed ShExC) and still supply a shape map whose
    /// `shape_label` is absent from the schema, or whose `focus_node` is
    /// an empty string -- both fail inside
    /// `shex_native::validate_shex_schema` (`"shape not declared in
    /// schema: {shape_label}"` / `"invalid focus node syntax: empty node
    /// string"`), a distinct failure mode from schema parsing. See
    /// `shex_validator_error_on_shape_label_absent_from_schema` (test,
    /// below) for the end-to-end reachability proof.
    #[error("ShEx validator error for profile `{profile_id}`: {reason}")]
    ShexValidatorError { profile_id: String, reason: String },
    /// A duplicate `correlation_id` was submitted with a different profile
    /// or graph than the first admission attempt that used it -- the
    /// idempotency+correlation gate refuses rather than silently
    /// overwriting or silently returning the wrong receipt.
    #[error(
        "correlation id `{correlation_id}` was already used for a different \
         admission attempt (first content digest `{first_digest}`, this \
         attempt's content digest `{this_digest}`)"
    )]
    DuplicateCorrelationConflict {
        correlation_id: String,
        first_digest: String,
        this_digest: String,
    },
    /// [`ShapeReceipt::verify`] recomputed a digest that differs from the
    /// one the receipt carries -- the receipt is not trusted, its identity
    /// is recomputed and compared.
    #[error(
        "shape receipt digest mismatch for profile `{profile_id}`: carried \
         `{carried}` but canonical material recomputes to `{recomputed}`"
    )]
    ReplayMismatch {
        profile_id: String,
        carried: String,
        recomputed: String,
    },
}

