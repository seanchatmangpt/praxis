// Admission Decision (D5) + Receipt (D6) + Handoff (D7: AdmittedGraph)
// ---------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AdmissionDecision {
    Admitted,
    Refused,
}

impl AdmissionDecision {
    pub const fn as_str(self) -> &'static str {
        match self {
            AdmissionDecision::Admitted => "ADMITTED",
            AdmissionDecision::Refused => "REFUSED",
        }
    }
}

/// BLAKE3 digest over the canonical `ViolationSet` + `AdmissionDecision`
/// material. Computed, never asserted: [`ShapeReceipt::verify`] recomputes
/// the digest from carried material and compares, matching this repo's
/// receipts-are-cryptographic-not-wishful doctrine
/// (`.claude/rules/rust-agi-core-team.md` rule 6).
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct ShapeReceipt {
    pub profile_id: String,
    pub decision: String,
    pub digest_hex: String,
    canonical_material: String,
}

impl ShapeReceipt {
    fn compute(violations: &ViolationSet, decision: AdmissionDecision) -> Self {
        let canonical_material = violations.canonical_material(&decision);
        let digest_hex = blake3::hash(canonical_material.as_bytes())
            .to_hex()
            .to_string();
        ShapeReceipt {
            profile_id: violations.profile_id.clone(),
            decision: decision.as_str().to_string(),
            digest_hex,
            canonical_material,
        }
    }

    /// Recomputes the digest from carried canonical material and compares
    /// it with the carried digest -- SHAPE_DECISION_REPLAYABLE: a receipt's
    /// identity is reconstructed, not trusted.
    pub fn verify(&self) -> Result<(), ShapeAdmissionRefused> {
        let recomputed = blake3::hash(self.canonical_material.as_bytes())
            .to_hex()
            .to_string();
        if recomputed != self.digest_hex {
            return Err(ShapeAdmissionRefused::ReplayMismatch {
                profile_id: self.profile_id.clone(),
                carried: self.digest_hex.clone(),
                recomputed,
            });
        }
        Ok(())
    }
}

/// The Admission Handoff's output (D7: AdmittedGraph in spirit -- carries
/// the decision + receipt a downstream planning stage consumes, rather than
/// the graph data itself, which the caller already holds).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdmissionHandoff {
    pub decision: AdmissionDecision,
    pub violations: ViolationSet,
    pub receipt: ShapeReceipt,
}

// ---------------------------------------------------------------------
// Idempotency + correlation gate (L7 chaos: duplicate events, restart
// recovery)
// ---------------------------------------------------------------------

/// Durable-in-intent (see module doc's honest PARTIAL disclosure)
/// idempotency+correlation gate. `BTreeMap` (not `HashMap`) so iteration
/// order -- and therefore [`ShapeAdmissionGate::persist`]'s JSON key order
/// -- is deterministic, per this repo's no-`HashMap`-iteration-without-
/// sorting determinism doctrine.
#[derive(Debug, Default)]
pub struct ShapeAdmissionGate {
    receipts_by_correlation: BTreeMap<String, (String, AdmissionHandoff)>,
}

impl ShapeAdmissionGate {
    pub fn new() -> Self {
        Self::default()
    }

    /// Runs the full F07 pipeline: Profile Resolver -> SHACL Validator ->
    /// ShEx Validator -> Violation Normalizer -> Refusal Emitter/Admission
    /// Decision -> Shape Receipt -> Admission Handoff.
    ///
    /// `correlation_id` identifies this admission attempt for idempotency:
    /// a second call with the same `correlation_id` and the same
    /// `(profile, graph_turtle)` returns the first call's handoff unchanged
    /// (SHAPE_ADMISSION_ALIVE's idempotency guarantee) rather than
    /// re-running the pipeline; a second call with the same
    /// `correlation_id` but a *different* `(profile, graph_turtle)` is
    /// refused with [`ShapeAdmissionRefused::DuplicateCorrelationConflict`]
    /// rather than silently overwriting the first attempt's receipt.
    ///
    /// A graph that fails to parse, or a malformed profile, is refused
    /// before `AdmissionState::Decided` is ever reached
    /// (MALFORMED_WORLD_PREPLAN_REFUSAL) -- it never becomes a planning
    /// state. A graph that parses but violates the declared shape law
    /// reaches `Decided`/`Receipted` normally, with
    /// `AdmissionDecision::Refused`: this is a decided, receipted, audited
    /// outcome, not a pipeline malfunction, so it is `Ok(handoff)`, not
    /// `Err`. A caller that treats anything other than
    /// `AdmissionDecision::Admitted` as "no standing granted" gets that
    /// property from `AdmissionHandoff::decision` either way.
    ///
    /// # Complexity
    /// O(bytes of graph_turtle) to parse + the SHACL/ShEx validators' own
    /// documented complexity (see `praxis_graphlaw::shacl::validate` and
    /// `shex_native::validate_shex_schema`) + O(v log v) to normalize/sort
    /// v violations. The idempotency lookup is O(log n) in the number of
    /// distinct correlation ids seen (`BTreeMap`).
    pub fn admit(
        &mut self,
        correlation_id: &str,
        profile: &ShapeProfile,
        graph_turtle: &str,
    ) -> Result<AdmissionHandoff, ShapeAdmissionRefused> {
        let content_digest =
            blake3::hash(format!("{}\u{1}{graph_turtle}", profile.profile_id).as_bytes())
                .to_hex()
                .to_string();

        if let Some((seen_digest, handoff)) = self.receipts_by_correlation.get(correlation_id) {
            return if *seen_digest == content_digest {
                Ok(handoff.clone())
            } else {
                Err(ShapeAdmissionRefused::DuplicateCorrelationConflict {
                    correlation_id: correlation_id.to_string(),
                    first_digest: seen_digest.clone(),
                    this_digest: content_digest,
                })
            };
        }

        // PROFILED
        profile.resolve()?;
        let _state = AdmissionState::Profiled;

        let mut store = TripleStore::new();
        store
            .load_triples(graph_turtle, Syntax::Turtle)
            .map_err(|reason| ShapeAdmissionRefused::GraphMalformed { reason })?;

        // SHACL_CHECKED
        let shacl_report =
            store
                .validate_shacl(&profile.shacl_shapes_turtle)
                .map_err(|reason| ShapeAdmissionRefused::ShaclValidatorError {
                    profile_id: profile.profile_id.clone(),
                    reason,
                })?;
        let _state = AdmissionState::ShaclChecked;

        // SHEX_CHECKED
        let shex_report = match &profile.shex {
            Some((schema_shexc, shape_map)) => Some(
                store
                    .validate_shex_c(schema_shexc, shape_map)
                    .map_err(|reason| ShapeAdmissionRefused::ShexValidatorError {
                        profile_id: profile.profile_id.clone(),
                        reason,
                    })?,
            ),
            None => None,
        };
        let _state = AdmissionState::ShexChecked;

        // VIOLATIONS_NORMALIZED
        let violations =
            ViolationSet::normalize(&profile.profile_id, &shacl_report, shex_report.as_ref());
        let _state = AdmissionState::ViolationsNormalized;

        // DECIDED
        let decision = if violations.shacl_conforms && violations.shex_conforms {
            AdmissionDecision::Admitted
        } else {
            AdmissionDecision::Refused
        };
        let _state = AdmissionState::Decided;

        // RECEIPTED
        let receipt = ShapeReceipt::compute(&violations, decision);
        let _state = AdmissionState::Receipted;

        // HANDED_OFF
        let handoff = AdmissionHandoff {
            decision,
            violations,
            receipt,
        };
        let _state = AdmissionState::HandedOff;

        self.receipts_by_correlation.insert(
            correlation_id.to_string(),
            (content_digest, handoff.clone()),
        );
        Ok(handoff)
    }

    /// Serializes the durable idempotency/receipt state (correlation id ->
    /// content digest + handoff) to JSON, `BTreeMap` order (deterministic).
    /// See the module doc comment's honest disclosure: this gives a real
    /// in-process persist/restore round trip, not wired to disk on every
    /// admission by this pass.
    pub fn persist(&self) -> Result<String, serde_json::Error> {
        let serializable: BTreeMap<&String, PersistedEntry<'_>> = self
            .receipts_by_correlation
            .iter()
            .map(|(k, (digest, handoff))| {
                (
                    k,
                    PersistedEntry {
                        content_digest: digest,
                        decision: handoff.decision.as_str(),
                        receipt: &handoff.receipt,
                        violations: &handoff.violations,
                    },
                )
            })
            .collect();
        serde_json::to_string(&serializable)
    }

    /// Restores gate state from [`ShapeAdmissionGate::persist`]'s JSON --
    /// simulates recovery after a restart: a fresh `ShapeAdmissionGate`
    /// that calls `restore` with a prior instance's `persist` output
    /// recognizes the same `correlation_id`s as already-admitted, without
    /// re-running the pipeline.
    pub fn restore(json: &str) -> Result<Self, serde_json::Error> {
        let parsed: BTreeMap<String, PersistedEntryOwned> = serde_json::from_str(json)?;
        let receipts_by_correlation = parsed
            .into_iter()
            .map(|(k, entry)| {
                let decision = if entry.decision == AdmissionDecision::Admitted.as_str() {
                    AdmissionDecision::Admitted
                } else {
                    AdmissionDecision::Refused
                };
                (
                    k,
                    (
                        entry.content_digest,
                        AdmissionHandoff {
                            decision,
                            violations: entry.violations,
                            receipt: entry.receipt,
                        },
                    ),
                )
            })
            .collect();
        Ok(ShapeAdmissionGate {
            receipts_by_correlation,
        })
    }

    /// Number of distinct correlation ids this gate has admitted -- used by
    /// tests to observe idempotency without inspecting private fields.
    pub fn admitted_count(&self) -> usize {
        self.receipts_by_correlation.len()
    }
}

#[derive(serde::Serialize)]
struct PersistedEntry<'a> {
    content_digest: &'a str,
    decision: &'static str,
    receipt: &'a ShapeReceipt,
    violations: &'a ViolationSet,
}

#[derive(serde::Deserialize)]
struct PersistedEntryOwned {
    content_digest: String,
    decision: String,
    receipt: ShapeReceipt,
    violations: ViolationSet,
}

impl serde::Serialize for ViolationSet {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        #[derive(serde::Serialize)]
        struct Repr<'a> {
            profile_id: &'a str,
            shacl_conforms: bool,
            shex_conforms: bool,
            violations: &'a [Violation],
        }
        Repr {
            profile_id: &self.profile_id,
            shacl_conforms: self.shacl_conforms,
            shex_conforms: self.shex_conforms,
            violations: &self.violations,
        }
        .serialize(s)
    }
}

impl<'de> serde::Deserialize<'de> for ViolationSet {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        #[derive(serde::Deserialize)]
        struct Repr {
            profile_id: String,
            shacl_conforms: bool,
            shex_conforms: bool,
            violations: Vec<Violation>,
        }
        let r = Repr::deserialize(d)?;
        Ok(ViolationSet {
            profile_id: r.profile_id,
            shacl_conforms: r.shacl_conforms,
            shex_conforms: r.shex_conforms,
            violations: r.violations,
        })
    }
}

impl serde::Serialize for Violation {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        #[derive(serde::Serialize)]
        struct Repr<'a> {
            source: &'static str,
            focus_node: &'a str,
            message: &'a str,
        }
        Repr {
            source: match self.source {
                ViolationSource::Shacl => "SHACL",
                ViolationSource::Shex => "SHEX",
            },
            focus_node: &self.focus_node,
            message: &self.message,
        }
        .serialize(s)
    }
}

impl<'de> serde::Deserialize<'de> for Violation {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        #[derive(serde::Deserialize)]
        struct Repr {
            source: String,
            focus_node: String,
            message: String,
        }
        let r = Repr::deserialize(d)?;
        let source = if r.source == "SHACL" {
            ViolationSource::Shacl
        } else {
            ViolationSource::Shex
        };
        Ok(Violation {
            source,
            focus_node: r.focus_node,
            message: r.message,
        })
    }
}

