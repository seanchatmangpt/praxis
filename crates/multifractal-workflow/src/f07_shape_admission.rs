    /// SHAPE_ADMISSION_ALIVE: a graph that satisfies the declared shape law
    /// is admitted end-to-end (PROFILED..HANDED_OFF) with a receipt.
    #[test]
    fn shape_admission_alive_conforming_graph_is_admitted() {
        let mut gate = ShapeAdmissionGate::new();
        let data = r#"
            @prefix ex: <http://example.org/> .
            ex:w1 a ex:Widget ; ex:status ex:Active .
        "#;
        let handoff = gate
            .admit("corr-1", &profile("p-alive"), data)
            .expect("conforming graph should be admitted, not refused");
        assert_eq!(handoff.decision, AdmissionDecision::Admitted);
        assert!(handoff.violations.violations.is_empty());
        handoff.receipt.verify().expect("receipt must self-verify");
    }

    /// A graph violating the declared shape law is decided+receipted as
    /// Refused (not admitted), never reaching HANDED_OFF standing -- the
    /// family invariant "a graph that violates declared shape law cannot
