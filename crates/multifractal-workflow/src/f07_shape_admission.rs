#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum AdmissionState {
    Profiled,
    ShaclChecked,
    ShexChecked,
    ViolationsNormalized,
    Decided,
    Receipted,
    HandedOff,
    Refused,
}

impl AdmissionState {
    /// All states, in pipeline order (matches `vocab::LIFECYCLE_STATES`).
    pub const ALL: [AdmissionState; 8] = [
        AdmissionState::Profiled,
        AdmissionState::ShaclChecked,
        AdmissionState::ShexChecked,
        AdmissionState::ViolationsNormalized,
        AdmissionState::Decided,
        AdmissionState::Receipted,
        AdmissionState::HandedOff,
        AdmissionState::Refused,
    ];

    /// The `SCREAMING_SNAKE_CASE` name matching this state's
    /// `vocab::LIFECYCLE_STATES` entry.
    pub const fn name(self) -> &'static str {
        match self {
            AdmissionState::Profiled => "PROFILED",
            AdmissionState::ShaclChecked => "SHACL_CHECKED",
            AdmissionState::ShexChecked => "SHEX_CHECKED",
            AdmissionState::ViolationsNormalized => "VIOLATIONS_NORMALIZED",
            AdmissionState::Decided => "DECIDED",
            AdmissionState::Receipted => "RECEIPTED",
            AdmissionState::HandedOff => "HANDED_OFF",
            AdmissionState::Refused => "REFUSED",
        }
    }
}

// ---------------------------------------------------------------------
// Violation Normalizer (D4: ViolationSet)
// ---------------------------------------------------------------------

/// One normalized violation, merged from either a SHACL `ValidationResult`
/// or a ShEx `ShexValidationFailure` into a single shape independent of
/// which validator produced it.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Violation {
    /// Which validator produced this violation.
    pub source: ViolationSource,
    /// The focus node the violation is about, decoded to a human-readable
    /// string via `praxis_graphlaw::encoding::Encoder::decode`.
    pub focus_node: String,
    /// Human-readable violation message. SHACL messages come from
    /// `ValidationResult::message` (falling back to the source constraint
    /// component IRI when the SHACL report carries no message); ShEx
    /// messages come from `ShexValidationFailure::reason`.
    pub message: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, serde::Serialize)]
pub enum ViolationSource {
    Shacl,
    Shex,
}

/// The single merged, deterministically-sorted violation set an
/// [`AdmissionDecision`] is decided from. Sorting by `(source, focus_node,
/// message)` makes the set's canonical serialization (and therefore the
/// [`ShapeReceipt`] digest computed from it) independent of the order the
/// two validators happened to emit results in.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ViolationSet {
    pub profile_id: String,
    pub shacl_conforms: bool,
    pub shex_conforms: bool,
    pub violations: Vec<Violation>,
}

impl ViolationSet {
    /// Merges a SHACL report and an optional ShEx report into one sorted
    /// `ViolationSet`. `shex_conforms` is `true` when no ShEx schema was
    /// configured (vacuous conformance, documented on [`ShapeProfile::shex`]).
    ///
    /// # Complexity
    /// O(n log n) where n = shacl results + shex failures (one sort pass).
    fn normalize(profile_id: &str, shacl: &ShaclReport, shex: Option<&ShexReport>) -> Self {
        let mut violations =
            Vec::with_capacity(shacl.results.len() + shex.map(|r| r.failures.len()).unwrap_or(0));
        for r in &shacl.results {
            let message = r.message.clone().unwrap_or_else(|| {
                praxis_graphlaw::encoding::Encoder::decode(&r.source_constraint_component.id())
                    .unwrap_or_else(|| "<undecodable constraint component>".to_string())
            });
            let focus_node = praxis_graphlaw::encoding::Encoder::decode(&r.focus_node.id())
                .unwrap_or_else(|| "<undecodable focus node>".to_string());
            violations.push(Violation {
                source: ViolationSource::Shacl,
                focus_node,
                message,
            });
        }
        if let Some(shex) = shex {
            for f in &shex.failures {
                let focus_node = praxis_graphlaw::encoding::Encoder::decode(&f.node.id())
                    .unwrap_or_else(|| "<undecodable focus node>".to_string());
                violations.push(Violation {
                    source: ViolationSource::Shex,
                    focus_node,
                    message: format!("shape {}: {}", f.shape, f.reason),
                });
            }
        }
        violations.sort();
        ViolationSet {
            profile_id: profile_id.to_string(),
            shacl_conforms: shacl.conforms,
            shex_conforms: shex.map(|r| r.conforms).unwrap_or(true),
            violations,
        }
    }

    /// Canonical serialization used as [`ShapeReceipt`] hash material:
    /// deterministic JSON (`serde_json` field order follows struct
    /// declaration order, not a `HashMap`, so this is stable across runs).
    fn canonical_material(&self, decision: &AdmissionDecision) -> String {
        // `.expect`, not `.unwrap_or_default()`: this struct's fields are plain
        // String/bool/Vec<Violation> (Violation itself is String/String/enum) --
        // no non-string map keys, no floats, no recursive types -- so
        // serde_json::to_string cannot fail for this type. Silently defaulting
        // to an empty string here would corrupt the receipt's hash material
        // (hashing "nothing" instead of the real violation set) without any
        // signal that it happened -- exactly the silent-default failure mode
        // this repo's receipts-are-cryptographic-not-wishful doctrine forbids.
        let material = serde_json::to_string(self)
            .expect("ViolationSet has no non-string map keys, floats, or recursive types");
        format!("{material}\u{1}{}", decision.as_str())
    }
}

