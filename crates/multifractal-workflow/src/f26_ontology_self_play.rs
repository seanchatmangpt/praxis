/// F26 self-play pipeline's typed refusal taxonomy. Every variant is
/// returned from a real code path exercised by this module's tests (see
/// each variant's doc comment for which stage raises it), except
/// [`SelfPlayRefusal::NotYetImplemented`], which is raised unconditionally
/// by the three HAND_WRITE_REQUIRED stubs ([`generate_scenario`],
/// [`mine_discovery_patterns`], [`capitalize_discoveries`]).
#[derive(Debug, Clone, thiserror::Error)]
pub enum SelfPlayRefusal {
    /// Raised unconditionally by a stage whose real algorithm does not yet
    /// exist anywhere in this repo or the family survey's three surveyed
    /// external candidates (confirmed by the survey's exhaustive negative
    /// grep). Never dressed up as a working implementation.
    #[error("F26 stage `{stage}` (V12-026) not yet implemented: {reason}")]
    NotYetImplemented {
        stage: &'static str,
        reason: &'static str,
    },
    /// [`contract_scenario_graph`]: the [`ScenarioGraph`]'s `facts_turtle`
    /// failed to parse (`TripleStore::load_triples`).
    #[error("scenario graph facts failed to parse as Turtle: {reason}")]
    WorldMalformed { reason: String },
    /// [`contract_scenario_graph`]: the supplied N3 rule set failed to
    /// parse (`TripleStore::load_rules`).
    #[error("contraction rule set failed to parse as N3: {reason}")]
    RuleSetMalformed { reason: String },
    /// [`contract_scenario_graph`]: `TripleStore::materialize` itself
    /// returned an error (distinct from "materialized zero derived
    /// triples", which is a normal, non-error outcome).
    #[error("datalog/N3 contraction (materialize) failed: {reason}")]
    ContractionFailed { reason: String },
    /// [`admit_contracted_world`]: the SHACL validator itself errored
    /// (distinct from a non-conforming report, which is the normal
    /// [`AdmissionDecision::Refused`] outcome, not this variant).
    #[error("SHACL validator error: {reason}")]
    ShaclValidatorError { reason: String },
    /// The named refusal type for D4 Shape Admission per the family
    /// survey. Raised by [`run_reused_pipeline`] (not by
    /// [`admit_contracted_world`] itself, which returns the refusal as
    /// *data* -- see its own doc comment) when a self-play world's
    /// [`AdmissionDecision`] is [`AdmissionVerdict::Refused`]: the
    /// WORLD_GENERATED -> REFUSED off-ramp (`vocab::REFUSAL_EXIT_STATES`).
    #[error(
        "self-play scenario refused at shape admission: {violation_count} SHACL violation(s): {violation_summary:?}"
    )]
    SelfPlayScenarioRefused {
        violation_count: usize,
        violation_summary: Vec<String>,
    },
    /// [`plan_goal_closure`]: the indexed PDDL8 grounder/planner could not
    /// close the goal (empty grounding or no admitted plan within the
    /// depth bound) -- the family's `IMPOSSIBLE_SCENARIO_PREPLAN_REFUSAL`
    /// exit-evidence flag (`vocab::EXIT_EVIDENCE_FLAGS`), and the
    /// PLANNED -> REFUSED off-ramp (`vocab::REFUSAL_EXIT_STATES`).
    #[error(
        "PDDL planner could not close the goal (impossible scenario, refused pre-plan): {reason}"
    )]
    ImpossibleScenarioPreplanRefused { reason: String },
    /// [`simulate_workflow`]: POWL projection or Turtle serialization
    /// refused (`chatman::powl_projection`'s own typed `Refusal`,
    /// stringified).
    #[error("POWL simulation refused: {reason}")]
    SimulationRefused { reason: String },
    /// [`execute_synthetic_hook`]: the hook's SPARQL CONSTRUCT query failed
    /// to parse or evaluate.
    #[error("synthetic hook SPARQL CONSTRUCT evaluation failed: {reason}")]
    SyntheticHookFailed { reason: String },
    /// [`SelfPlayGate::check`]: a duplicate `correlation_id` was submitted
    /// with different content than the first attempt that used it -- the
    /// idempotency+correlation gate refuses rather than silently
    /// overwriting or silently replaying the wrong result. Part of the
    /// family's L7 chaos-gating requirement.
    #[error(
        "correlation id `{correlation_id}` was already used for a different self-play attempt \
         (first content digest `{first_digest}`, this attempt's content digest `{this_digest}`)"
    )]
    DuplicateCorrelationConflict {
        correlation_id: String,
        first_digest: String,
        this_digest: String,
    },
}

