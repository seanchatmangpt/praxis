/// D3: the Datalog/N3 contraction's derived-triple delta over a
/// [`ScenarioGraph`]. `derived_nquads` is the real materialized output of
/// `praxis_graphlaw::TripleStore::materialize`, decoded and sorted into
/// canonical order (never HashMap iteration order) before any receipt would
/// hash it, per this repo's determinism doctrine.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClosureDelta {
    pub derived_nquads: Vec<String>,
}

/// Datalog N3 Contraction (D3): parses `world.facts_turtle` and `rules_n3`
/// with `praxis_graphlaw::TripleStore::load_triples`/`load_rules` (both
/// real parsers that surface errors, unlike `TripleStore::from`, which
/// silently empties on a parse failure -- deliberately not used here), then
/// runs the real stratified semi-naive Datalog/N3 materialization to a
/// fixpoint. Returns the mutated store (already carrying the closure, for
/// [`admit_contracted_world`] to validate directly -- no re-serialization
/// round trip) alongside the [`ClosureDelta`].
///
/// # Complexity
/// O(parse) + whatever `TripleStore::materialize`'s stratified semi-naive
/// evaluation costs for `rules_n3`'s rule set (bounded by
/// `praxis_graphlaw::reasoner::Reasoner::materialize`'s own documented
/// bound, not re-derived here).
pub fn contract_scenario_graph(
    world: &ScenarioGraph,
    rules_n3: &str,
) -> Result<(TripleStore, ClosureDelta), SelfPlayRefusal> {
    let mut store = TripleStore::new();
    store
        .load_triples(&world.facts_turtle, Syntax::Turtle)
        .map_err(|reason| SelfPlayRefusal::WorldMalformed { reason })?;
    store
        .load_rules(rules_n3)
        .map_err(|reason| SelfPlayRefusal::RuleSetMalformed { reason })?;
    let derived = store
        .materialize()
        .map_err(|reason| SelfPlayRefusal::ContractionFailed { reason })?;
    let mut derived_nquads: Vec<String> = derived
        .iter()
        .map(|t| TripleStore::decode_triple(t))
        .collect();
    derived_nquads.sort();
    Ok((store, ClosureDelta { derived_nquads }))
}

