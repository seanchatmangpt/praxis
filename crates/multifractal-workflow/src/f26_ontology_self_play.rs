// ---------------------------------------------------------------------
// L7: idempotency + correlation gate (real, in-memory; disclosed scope)
// ---------------------------------------------------------------------

/// Outcome of [`SelfPlayGate::check`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GateOutcome {
    /// First time this `correlation_id` has been seen.
    Fresh,
    /// This `correlation_id` was seen before with byte-identical content --
    /// a duplicate submission (e.g. a retried event or a restarted engine
    /// re-processing the same self-play attempt), not an error.
    Replayed,
}

/// L7 idempotency+correlation gate: the family's requirement that
/// "duplicate event, process/engine restart, stale/malformed result" chaos
/// resolves via an atomic idempotency+correlation gate, never an
/// inconsistent state. Real, in-memory (`BTreeMap<String, String>`,
/// deterministic iteration order per this repo's doctrine); see the module
/// doc comment for the disclosed persist/restore scope.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct SelfPlayGate {
    seen: BTreeMap<String, String>,
}

impl SelfPlayGate {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Checks `correlation_id` against `content`'s BLAKE3 digest.
    /// - Unseen `correlation_id` -> [`GateOutcome::Fresh`], and the digest
    ///   is recorded.
    /// - Seen `correlation_id` with the same digest -> [`GateOutcome::Replayed`]
    ///   (idempotent re-submission, e.g. a retried duplicate event or a
    ///   restarted engine re-processing the same attempt).
    /// - Seen `correlation_id` with a *different* digest ->
    ///   [`SelfPlayRefusal::DuplicateCorrelationConflict`] (a stale or
    ///   malformed result masquerading under a reused correlation id is
    ///   refused, never silently accepted).
    ///
    /// # Complexity
    /// O(log n) in the number of distinct correlation ids seen (`BTreeMap`).
    pub fn check(
        &mut self,
        correlation_id: &str,
        content: &str,
    ) -> Result<GateOutcome, SelfPlayRefusal> {
        let digest = blake3::hash(content.as_bytes()).to_hex().to_string();
        match self.seen.get(correlation_id) {
            Some(seen_digest) if *seen_digest == digest => Ok(GateOutcome::Replayed),
            Some(seen_digest) => Err(SelfPlayRefusal::DuplicateCorrelationConflict {
                correlation_id: correlation_id.to_string(),
                first_digest: seen_digest.clone(),
                this_digest: digest,
            }),
            None => {
                self.seen.insert(correlation_id.to_string(), digest);
                Ok(GateOutcome::Fresh)
            }
        }
    }

    /// Serializes the in-memory correlation map to JSON (`BTreeMap` order,
    /// deterministic). Real serialize/deserialize round trip; see the
    /// module doc comment for the disclosed scope (not wired to disk
    /// automatically).
    pub fn persist(&self) -> Result<String, serde_json::Error> {
        serde_json::to_string(&self.seen)
    }

    /// Restores a gate from [`SelfPlayGate::persist`]'s JSON.
    pub fn restore(json: &str) -> Result<Self, serde_json::Error> {
        Ok(Self {
            seen: serde_json::from_str(json)?,
        })
    }
}

// ---------------------------------------------------------------------
// Orchestrator: the real middle-stage chain (D3 -> D4 -> D5 -> D6 -> D7)
// ---------------------------------------------------------------------

/// Output of [`run_reused_pipeline`]: everything the real, reused stages
/// (D3-D7) produced for one admitted, planned, simulated self-play world.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReusedPipelineOutput {
    pub closure: ClosureDelta,
    pub admission: AdmissionDecision,
    pub receipt: ScenarioReceipt,
}

/// Runs the real, reused D3->D4->D5->D6->D7 chain over a caller-supplied
/// [`ScenarioGraph`] (since D2 [`generate_scenario`] cannot produce one
/// yet -- see the module doc comment).
///
/// Refuses at the WORLD_GENERATED -> REFUSED off-ramp
/// ([`SelfPlayRefusal::SelfPlayScenarioRefused`]) if [`admit_contracted_world`]
/// decides [`AdmissionVerdict::Refused`]; refuses at the PLANNED -> REFUSED
/// off-ramp ([`SelfPlayRefusal::ImpossibleScenarioPreplanRefused`]) if
/// [`plan_goal_closure`] cannot close the goal. Both off-ramps are named in
/// `vocab::REFUSAL_EXIT_STATES`, transcribed from the survey's own state
/// machine description ("REFUSED exits from WORLD_GENERATED and PLANNED").
#[allow(clippy::too_many_arguments)]
pub fn run_reused_pipeline(
    world: &ScenarioGraph,
    rules_n3: &str,
    shapes_turtle: &str,
    domain: &Pddl8Domain,
    problem: &Pddl8Problem,
    base_iri: &str,
    hook_name: &str,
    construct_query: &str,
) -> Result<ReusedPipelineOutput, SelfPlayRefusal> {
    // CONTRACTED
    let (store, closure) = contract_scenario_graph(world, rules_n3)?;

    // ADMITTED (or the WORLD_GENERATED -> REFUSED off-ramp)
    let admission = admit_contracted_world(&store, shapes_turtle)?;
    if admission.verdict == AdmissionVerdict::Refused {
        return Err(SelfPlayRefusal::SelfPlayScenarioRefused {
            violation_count: admission.violation_count,
            violation_summary: admission.violation_summary,
        });
    }

    // PLANNED (or the PLANNED -> REFUSED off-ramp, raised inside plan_goal_closure)
    let plan = plan_goal_closure(domain, problem)?;

    // SIMULATED
    let workflow = simulate_workflow(&plan, base_iri)?;

    // MINED's prerequisite: the D7 synthetic hook receipt.
    let receipt = execute_synthetic_hook(&workflow, hook_name, construct_query)?;

    Ok(ReusedPipelineOutput {
        closure,
        admission,
        receipt,
    })
}

