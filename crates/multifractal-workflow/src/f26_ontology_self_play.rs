/// D7: the Synthetic Hook Surface's execution receipt over a
/// [`SimulatedWorkflow`]. Wraps the real, already-defined
/// `praxis_graphlaw::hooks::HookReceipt` type (idempotency-key/delta-hash
/// shape) rather than inventing a parallel receipt shape.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ScenarioReceipt {
    pub hook_receipt: HookReceipt,
    pub additions_count: usize,
    pub deletions_count: usize,
}

/// Synthetic Hook Surface (D7): parses `workflow.turtle`, runs
/// `hook_name`'s `construct_query` through
/// `praxis_graphlaw::hooks::evaluate_construct` (the real SPARQL CONSTRUCT
/// engine), then builds a [`ScenarioReceipt`] the same way
/// `praxis_graphlaw::hooks::serialize_delta_quad` + BLAKE3 already do for
/// production hook receipts elsewhere in this repo (`HookReceipt`'s own
/// doc). Additions/deletions are sorted into canonical order by their
/// `TripleStore::decode_triple` string form *before* serialization, so the
/// delta-quad material -- and therefore `delta_hash` -- is receipt-stable
/// regardless of `evaluate_construct`'s internal binding order.
///
/// This is the *mechanism* this stage needs, real and reused; the *policy*
/// of which hooks fire on a self-play world (a hook registry keyed off
/// scenario dimensions) is not implemented -- the caller supplies
/// `hook_name`/`construct_query` directly, same disclosed scope as
/// `f08_pddl_planning`'s hook_binder refusal for the same underlying gap
/// (no general hook-registry query API exists anywhere in this repo).
pub fn execute_synthetic_hook(
    workflow: &SimulatedWorkflow,
    hook_name: &str,
    construct_query: &str,
) -> Result<ScenarioReceipt, SelfPlayRefusal> {
    let mut store = TripleStore::new();
    store
        .load_triples(&workflow.turtle, Syntax::Turtle)
        .map_err(|reason| SelfPlayRefusal::WorldMalformed { reason })?;
    let (mut additions, mut deletions) =
        evaluate_construct(construct_query, &store.triple_index)
            .map_err(|reason| SelfPlayRefusal::SyntheticHookFailed { reason })?;
    additions.sort_by_key(|t| TripleStore::decode_triple(t));
    deletions.sort_by_key(|t| TripleStore::decode_triple(t));

    let mut lines = Vec::new();
    for t in &additions {
        serialize_delta_quad(hook_name, t, true, &mut lines);
    }
    for t in &deletions {
        serialize_delta_quad(hook_name, t, false, &mut lines);
    }
    let delta_quads = lines.join("\n");
    let delta_hash = blake3::hash(delta_quads.as_bytes()).to_hex().to_string();
    let idempotency_key = blake3::hash(format!("{hook_name}\u{1}{delta_hash}").as_bytes())
        .to_hex()
        .to_string();

    Ok(ScenarioReceipt {
        hook_receipt: HookReceipt {
            hook_name: hook_name.to_string(),
            delta_hash,
            idempotency_key,
            delta_quads,
        },
        additions_count: additions.len(),
        deletions_count: deletions.len(),
    })
}

