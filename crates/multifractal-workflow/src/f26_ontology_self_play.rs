/// D4 verdict. Modeled as plain data returned inside `Ok`, mirroring
/// `f07_shape_admission.rs`'s `AdmissionDecision` -- "refused" is a normal
/// pipeline outcome the caller inspects, not a Rust `Err`. The typed
/// [`SelfPlayRefusal::SelfPlayScenarioRefused`] error is raised one layer up,
/// by [`run_reused_pipeline`], when it decides to stop the pipeline because
/// of this verdict.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AdmissionVerdict {
    Admitted,
    Refused,
}

/// D4: Shape Admission's admit/refuse verdict over a contracted world.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdmissionDecision {
    pub verdict: AdmissionVerdict,
    pub violation_count: usize,
    pub violation_summary: Vec<String>,
}

/// Shape Admission (D4): thin call into
/// `praxis_graphlaw::TripleStore::validate_shacl` -- real, already-tested
/// SHACL validation (5000+ lines, W3C-conformance-tested), no constraint
/// logic reimplemented here. Runs against `store` *after*
/// [`contract_scenario_graph`] has materialized it in place, so admission
/// sees the closed world, not just the asserted facts.
///
/// # Complexity
/// O(SHACL validator's own bound over `store`'s triple count and
/// `shapes_turtle`'s shape count) -- not re-derived here.
pub fn admit_contracted_world(
    store: &TripleStore,
    shapes_turtle: &str,
) -> Result<AdmissionDecision, SelfPlayRefusal> {
    let report: ShaclReport = store
        .validate_shacl(shapes_turtle)
        .map_err(|reason| SelfPlayRefusal::ShaclValidatorError { reason })?;
    if report.conforms {
        Ok(AdmissionDecision {
            verdict: AdmissionVerdict::Admitted,
            violation_count: 0,
            violation_summary: Vec::new(),
        })
    } else {
        let mut violation_summary: Vec<String> = report
            .results
            .iter()
            .map(|r| {
                format!(
                    "{:?} at {:?} (severity {:?})",
                    r.source_constraint_component, r.focus_node, r.severity
                )
            })
            .collect();
        violation_summary.sort();
        Ok(AdmissionDecision {
            verdict: AdmissionVerdict::Refused,
            violation_count: report.results.len(),
            violation_summary,
        })
    }
}

