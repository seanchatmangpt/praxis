/// Structurally greps the merged, parsed `AdmittedSurface`'s action
/// effects for the two forbidden substrings the compliance-overclaim fence
/// bans: "compliant" and "opinion" (case-insensitive). This is the
/// mechanical half of the fence — the doc-comment half states the rule,
/// this function (and `soc2_test.rs`'s use of it) makes a violation
/// impossible to miss.
///
/// # Errors
/// `CNG_R05 UnsupportedConstruct` naming the first action/predicate that
/// violates the fence.
///
/// # Complexity
/// O(actions × effects) over the merged surface.
pub fn verify_no_compliance_or_opinion_effects(
    surface: &AdmittedSurface,
) -> Result<(), CngRefusal> {
    for action in &surface.domain.actions {
        for effect in action.add_effects.iter().chain(action.del_effects.iter()) {
            let lowered = effect.pred.to_ascii_lowercase();
            if lowered.contains("compliant") || lowered.contains("opinion") {
                return Err(CngRefusal::UnsupportedConstruct(format!(
                    "compliance-overclaim fence violated: action `{}` has an effect atom \
                     `{}` naming a compliance verdict or auditor opinion; the only lawful \
                     terminal deliverable is evidence-bundle-complete",
                    action.name, effect.pred
                )));
            }
        }
    }
    Ok(())
}

/// SOC2 evidence-bundle metrics (v26.7.12/13 Stage 2): two measured SELECT
/// counts over the case-study INSTANCE graph via the on-disk
/// `metric-soc2-*.rq` queries, plus one DERIVED_ARITHMETIC ratio computed in
/// Rust from those two counts. Mirrors `report.rs`'s
/// `ModeledLlmComparison`/`DerivedScaleExtrapolation` measurement-class
/// separation exactly: never merged into `RunReport`, and the derived field
/// is explicitly tagged so no reader can mistake Rust division for a third
/// SPARQL aggregate (this crate's SPARQL engine typed-refuses
/// GROUP_CONCAT/SAMPLE; ratios are computed here, never in a query).
///
/// # COMPLIANCE-OVERCLAIM FENCE
/// Every field is an evidence-bundle measurement over the engagement-process
/// graph — none is, or implies, a compliance verdict or auditor opinion. See
/// this module's top doc comment for the full fence disclosure.
#[derive(Debug, serde::Serialize)]
pub struct Soc2EvidenceMetrics {
    pub measurement_class: &'static str,
    /// metric-soc2-evidenced-controls.rq: COUNT DISTINCT control points
    /// (`prov:Plan`) carrying a complete evidentiary record (notation +
    /// design attribution + TSC-category mapping).
    pub evidenced_controls: u64,
    /// metric-soc2-exceptions.rq: COUNT DISTINCT exception-register
    /// deliverable entities generated by the Exception Identification
    /// phase activity.
    pub exception_register_artifacts: u64,
    /// metric-soc2-remediation-status.rq: COUNT DISTINCT management-
    /// response/remediation-log deliverable entities generated by the
    /// Management Response & Remediation phase activity.
    pub remediation_log_artifacts: u64,
    /// `exception_register_artifacts as f64 / evidenced_controls as f64`,
    /// computed in Rust from the two measured counts above — never a SPARQL
    /// aggregate. `0.0` when `evidenced_controls == 0` (division-by-zero
    /// refused silently would violate the no-silent-defaults invariant;
    /// `0.0` is the documented, deliberate convention this field uses when
    /// there is no denominator, not a fabricated measurement). Tagged by
    /// `derived_exception_register_ratio_class` below.
    pub derived_exception_register_ratio: f64,
    /// Machine-readable tag for `derived_exception_register_ratio`: always
    /// [`Soc2EvidenceMetrics::DERIVED_ARITHMETIC`], carried as a field (not
    /// only a doc comment) so a JSON reader of this struct's serialized form
    /// — e.g. the case-study bundle's evidence-metrics.json — cannot mistake
    /// the one derived field for a fourth measured SPARQL count, mirroring
    /// how `report.rs::DerivedScaleExtrapolation` tags its own fully-derived
    /// fields at the whole-struct level via `measurement_class`.
    pub derived_exception_register_ratio_class: &'static str,
}

impl Soc2EvidenceMetrics {
    pub const MEASUREMENT_CLASS: &'static str = "SOC2_EVIDENCE_BUNDLE_METRICS";
    /// Tag for the one field in this struct that is Rust arithmetic over
    /// two measured counts, not a third measurement.
    pub const DERIVED_ARITHMETIC: &'static str = "DERIVED_ARITHMETIC";
}

/// Loads `instance_ttl_path` (a SOC2 case-study instance-data file, e.g.
/// `tests/fixtures/soc2/solace-case-study.ttl`) into a fresh store and runs
/// the 3 on-disk `metric-soc2-*.rq` COUNT queries over it, returning the
/// measured counts plus the one Rust-computed DERIVED_ARITHMETIC ratio.
///
/// # Errors
/// `CNG_R10 IoRefused` for an unreadable file; `CNG_R01 MalformedTtl` for a
/// Turtle parse failure; `CNG_R05 UnsupportedConstruct` if a required query
/// is missing from `queries`.
///
/// # Complexity
/// O(instance graph size) parse + 3 O(graph) COUNT queries.
pub fn compute_evidence_metrics(
    instance_ttl_path: &Path,
    queries: &QuerySet,
) -> Result<Soc2EvidenceMetrics, CngRefusal> {
    let turtle = fs::read_to_string(instance_ttl_path)
        .map_err(|e| CngRefusal::IoRefused(format!("read {}: {e}", instance_ttl_path.display())))?;
    let store = Store::new().map_err(|e| CngRefusal::IoRefused(format!("store: {e}")))?;
    store
        .load_from_slice(RdfParser::from_format(RdfFormat::Turtle), turtle.as_bytes())
        .map_err(|e| {
            CngRefusal::MalformedTtl(format!(
                "{}: Turtle parse failed: {e}",
                instance_ttl_path.display()
            ))
        })?;

    let evidenced_controls = metric_count(
        &store,
        queries.get("metric-soc2-evidenced-controls")?,
        "metric-soc2-evidenced-controls",
    )?;
    let exception_register_artifacts = metric_count(
        &store,
        queries.get("metric-soc2-exceptions")?,
        "metric-soc2-exceptions",
    )?;
    let remediation_log_artifacts = metric_count(
        &store,
        queries.get("metric-soc2-remediation-status")?,
        "metric-soc2-remediation-status",
    )?;
    let derived_exception_register_ratio = if evidenced_controls == 0 {
        0.0
    } else {
        exception_register_artifacts as f64 / evidenced_controls as f64
    };

    Ok(Soc2EvidenceMetrics {
        measurement_class: Soc2EvidenceMetrics::MEASUREMENT_CLASS,
        evidenced_controls,
        exception_register_artifacts,
        remediation_log_artifacts,
        derived_exception_register_ratio,
        derived_exception_register_ratio_class: Soc2EvidenceMetrics::DERIVED_ARITHMETIC,
    })
}

