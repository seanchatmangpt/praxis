/// The 8-constraint split law for the ADM cycle: every action schema in the
/// merged surface stays inside the PDDL8 bounds (≤ 8 parameters, ≤ 8
/// precondition conjuncts, ≤ 8 add-effect conjuncts, ≤ 8 del-effect
/// conjuncts) and the merged goal — the union of every fragment's goal —
/// stays ≤ 8 conjuncts. The cycle fixtures satisfy this by construction
/// (chained 1-conjunct preconditions carry the phase ordering; only the
/// terminal fragment declares a goal atom), but the law is verified
/// mechanically here rather than assumed, so a future fragment that
/// concentrates constraints in one conjunction refuses loudly instead of
/// failing deep inside grounding.
///
/// # Errors
/// `CNG_R05 UnsupportedConstruct` naming the first violating action or the
/// oversized goal.
///
/// # Complexity
/// O(actions) over the merged surface.
pub fn verify_eight_constraint_split(surface: &AdmittedSurface) -> Result<(), CngRefusal> {
    const BOUND: usize = 8;
    for action in &surface.domain.actions {
        for (kind, len) in [
            ("parameters", action.params.len()),
            ("precondition conjuncts", action.preconditions.len()),
            ("add-effect conjuncts", action.add_effects.len()),
            ("del-effect conjuncts", action.del_effects.len()),
        ] {
            if len > BOUND {
                return Err(CngRefusal::UnsupportedConstruct(format!(
                    "8-constraint split violated: action `{}` has {len} {kind} (bound {BOUND})",
                    action.name
                )));
            }
        }
    }
    let goal_len = surface.problem.goal.len();
    if goal_len > BOUND {
        return Err(CngRefusal::UnsupportedConstruct(format!(
            "8-constraint split violated: merged goal has {goal_len} conjuncts (bound {BOUND}); \
             phase ordering must be carried by precondition chains, not goal conjuncts"
        )));
    }
    Ok(())
}

