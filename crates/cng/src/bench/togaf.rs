//! TOGAF ADM lifecycle case study — Meridian Global Carrier (v26.7.13).
//!
//! Drives the ENTIRE Architecture Development Method (Preliminary + Phases
//! A–H + Requirements Management) through the real cng manufacture chain:
//! the 10 phase fixtures under `tests/fixtures/togaf/` are domain FRAGMENTS
//! of one shared `meridian-adm-cycle` STRIPS domain (each contributing that
//! phase's 3 actions, chained by phase-completion predicates), plus one
//! problem fragment carrying the single init atom and the single terminal
//! goal atom. `pipeline::import_artifacts` admits them, `generate_plan`
//! grounds + plans the full 30-step cycle, and
//! `pipeline::hierarchical_projection` groups the plan back into 10 phase
//! children by artifact provenance — the ADM cycle as a hierarchical POWL.
//!
//! Fixture vocabulary is PUBLIC-ontology-first (blank nodes +
//! `skos:notation` handles; togaf content metamodel / skos / prov /
//! dcterms). The only private namespaces touched are the pipeline's own
//! ABI: `urn:chatman:engine#pddlDomain`/`#pddlProblem` (PDDL text carrier,
//! `pipeline.rs`) and the `powl2:` output vocabulary (`powl.rs`). See
//! `packs/togaf-adm-pack/ontology.ttl` for the disclosure.
//!
//! Generated by `packs/togaf-adm-pack` templates; the pack's ontology graph
//! unions `crates/cng/ontologies/pddl-strips.ttl` via the `ggen.toml`
//! `extra_ontologies` entry rather than a committed-union script.

