def ownership_data(surfaces: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    ownership: list[dict[str, Any]] = []
    fences: list[dict[str, Any]] = []
    outputs: dict[str, list[str]] = {}
    merge_laws: dict[str, str] = {}
    collisions: list[dict[str, Any]] = []
    retirement: list[dict[str, Any]] = []

    for surface in surfaces:
        path = str(surface["path"])
        owner = str(surface.get("semantic_owner") or "UNKNOWN")
        generated = bool(surface.get("generated"))
        generator = surface.get("generator")
        output_owners = [owner]
        outputs[path] = output_owners
        if generated and not generator:
            collisions.append(
                {"code": "CMD-G1-GENERATOR-UNKNOWN", "path": path, "classification": "unknown"}
            )
        text = read_tracked_text(path, str(surface["mode"]))
        direct = bool(text and DIRECT_ACTUATOR.search(text))
        ownership.append(
            {
                "surface": path,
                "semantic_owner": owner,
                "operational_owner": surface.get("operational_owner") or "UNKNOWN",
                "generator": generator or "NONE",
                "consumers": detect_load_path(path) or ["UNKNOWN"],
                "load_path": detect_load_path(path) or ["UNKNOWN"],
                "inputs": [generator] if generator else ["UNKNOWN"],
                "outputs": [path],
                "mutation_scope": path if generated else "NONE_OR_RUNTIME_DEFINED",
                "evidence_produced": ["Git object identity"],
                "failure_behavior": "typed by owning subsystem or UNKNOWN",
                "retirement_dependency": "exact-boundary equivalence and replay",
                "standing": "PARTIAL_ALIVE" if owner != "UNKNOWN" else "UNKNOWN",
                "lifecycle": "ACTIVE",
                "exclusive": True,
                "direct_actuator_signal": direct,
            }
        )
        fences.append(
            {
                "surface": path,
                "why_it_exists": surface["classification"],
                "who_calls_it": detect_load_path(path) or ["UNKNOWN"],
                "what_it_owns": [path] if generated else ["semantic behavior at its load path"],
                "what_it_mutates": [path] if generated else ["UNKNOWN_OR_NONE"],
                "evidence_it_emits": ["Git object identity"],
                "how_it_fails": "owning subsystem contract or UNKNOWN",
                "compatibility_contract": "current repository load path",
                "replacement_requirement": "same object, boundary, failure semantics, receipts, replay",
            }
        )
        if direct:
            collisions.append(
                {
                    "code": "CMD-G1-DIRECT-ACTUATOR-SIGNAL",
                    "path": path,
                    "classification": "review-required",
                }
            )
        if generated:
            retirement.append(
                {
                    "surface": path,
                    "candidate": False,
                    "reason": "generated projection retained; source authority must be preserved",
                    "checkpoint": "G9 exact replay",
                }
            )

    kernel.verify_ownership(outputs, merge_laws)
    return {
        "ownership": ownership,
        "fences": fences,
        "collisions": collisions,
        "retirement": retirement,
        "outputs": outputs,
        "merge_laws": merge_laws,
    }


