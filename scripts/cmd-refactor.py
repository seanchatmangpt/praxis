def git_identity() -> dict[str, str]:
    head = run("git", "rev-parse", "HEAD")
    tree = run("git", "rev-parse", "HEAD^{tree}")
    remote = run("git", "config", "--get", "remote.origin.url", check=False)
    branch = run("git", "rev-parse", "--abbrev-ref", "HEAD")
    base_ref = os.environ.get("CMD_BASE_REF", branch)
    base_commit = os.environ.get("CMD_BASE_SHA", head)
    return {
        "repository": remote or "UNKNOWN",
        "head_ref": branch,
        "head_commit_sha": head,
        "head_tree_sha": tree,
        "base_ref": base_ref,
        "base_commit_sha": base_commit,
    }


def parse_index() -> list[dict[str, str]]:
    raw = run_bytes("git", "ls-files", "-s", "-z")
    result: list[dict[str, str]] = []
    for record in raw.split(b"\0"):
        if not record:
            continue
        header, path_bytes = record.split(b"\t", 1)
        mode, oid, stage = header.decode("ascii").split()
        path = path_bytes.decode("utf-8", "surrogateescape")
        result.append({"path": path, "mode": mode, "oid": oid, "stage": stage})
    return sorted(result, key=lambda row: (row["path"], row["stage"]))


def parse_tree() -> list[dict[str, str]]:
    raw = run_bytes("git", "ls-tree", "-r", "-t", "-z", "HEAD")
    result: list[dict[str, str]] = []
    for record in raw.split(b"\0"):
        if not record:
            continue
        header, path_bytes = record.split(b"\t", 1)
        mode, object_type, oid = header.decode("ascii").split()
        path = path_bytes.decode("utf-8", "surrogateescape")
        result.append(
            {"path": path, "mode": mode, "object_type": object_type, "oid": oid}
        )
    return sorted(result, key=lambda row: (row["path"], row["object_type"]))


def tracked_leaf_tree() -> list[dict[str, str]]:
    return [row for row in parse_tree() if row["object_type"] in {"blob", "commit"}]


def file_kind(mode: str, object_type: str) -> str:
    if mode == "100755":
        return "executable file"
    if mode == "120000":
        return "symlink"
    if mode == "160000" or object_type == "commit":
        return "gitlink/submodule"
    if mode == "100644":
        return "regular file"
    return "unknown"


def read_tracked_text(path: str, mode: str) -> str | None:
    if mode in {"120000", "160000"}:
        return None
    full = ROOT / path
    try:
        data = full.read_bytes()
    except OSError:
        return None
    if len(data) > TEXT_LIMIT or b"\0" in data[:8192]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def classify_path(path: str, mode: str, text: str | None) -> str:
    lower = path.lower()
    name = Path(path).name
    suffix = Path(path).suffix.lower()
    if path in {"AGENTS.md", "CLAUDE.md", "CHATGPT-CLOUD-AGENTS.md"} or path.startswith(
        ".claude/rules/"
    ):
        return "authored constitution"
    if mode == "160000":
        return "configuration"
    if text and GENERATED_HEADER.search("\n".join(text.splitlines()[:80])):
        return "generated consequence"
    if suffix in {".tmpl", ".tera", ".j2"} or "/templates/" in f"/{lower}":
        return "template"
    if "/fixtures/" in f"/{lower}" or lower.startswith("fixtures/"):
        return "fixture"
    if lower.startswith((".ggen/", ".cargo-cicd/", "receipts/")):
        return "evidence"
    if lower.startswith(".github/workflows/"):
        return "workflow"
    if name in {
        "Cargo.toml",
        "Cargo.lock",
        "ggen.toml",
        "ggen.lock",
        "justfile",
        "Makefile",
        "Dockerfile",
        "package.json",
        "pnpm-lock.yaml",
        "pyproject.toml",
        "rebar.config",
    } or suffix in {".yml", ".yaml", ".toml"}:
        return "configuration"
    if suffix in {".ttl", ".n3", ".rq", ".sparql", ".pddl", ".owl", ".shacl"}:
        return "domain source"
    if suffix in {
        ".rs", ".py", ".sh", ".bash", ".zsh", ".ts", ".tsx", ".js",
        ".mjs", ".cjs", ".erl", ".hrl", ".ex", ".exs", ".lean", ".c",
        ".h", ".cpp", ".hpp", ".java", ".kt", ".go", ".wat", ".tf",
    }:
        return "implementation"
    if suffix in {".md", ".rst", ".adoc", ".txt"} or lower.startswith("docs/"):
        return "documentation"
    if suffix in {".zip", ".gz", ".xz", ".bz2", ".tar", ".tgz"}:
        return "archive"
    if suffix in {".png", ".jpg", ".jpeg", ".gif", ".svg", ".pdf", ".wasm", ".bin", ".lock"}:
        return "asset"
    return "unknown"


def infer_owner(path: str) -> str:
    parts = Path(path).parts
    if len(parts) >= 2 and parts[0] in {"crates", "apps", "clients", "packs"}:
        return f"{parts[0]}/{parts[1]}"
    if parts and parts[0] == ".github":
        return ".github"
    if parts and parts[0] == "scripts":
        return "repository-automation"
    if parts and parts[0] == "docs":
        return "repository-documentation"
    return "repository-root"


def infer_generator(text: str | None) -> str | None:
    if not text:
        return None
    header = "\n".join(text.splitlines()[:100])
    match = SOURCE_HEADER.search(header)
    return match.group(1).strip().strip("*/ ") if match else None


def detect_load_path(path: str) -> list[str]:
    name = Path(path).name
    if name == "Cargo.toml":
        return ["cargo workspace/package manifest"]
    if name == "ggen.toml":
        return ["ggen root manifest"]
    if path.startswith(".github/workflows/"):
        return ["GitHub Actions workflow discovery"]
    if "/templates/" in f"/{path}" or Path(path).suffix in {".tmpl", ".tera"}:
        return ["ggen pack template discovery"]
    if path.endswith(".rs"):
        return ["Rust module or target discovery"]
    if path.endswith((".ttl", ".n3", ".rq", ".sparql", ".pddl")):
        return ["semantic graph/rule/query loader"]
    if path.endswith((".py", ".sh")) and path.startswith("scripts/"):
        return ["explicit operator command"]
    return []


def observe_data() -> dict[str, Any]:
    identity = git_identity()
    index = parse_index()
    tree = parse_tree()
    leaves = [row for row in tree if row["object_type"] in {"blob", "commit"}]
    index_stage0 = [row for row in index if row["stage"] == "0"]
    index_map = {row["path"]: row for row in index_stage0}
    leaf_map = {row["path"]: row for row in leaves}
    if set(index_map) != set(leaf_map):
        raise kernel.Refusal(
            "CMD-G0-EXACT-SET",
            f"index/tree mismatch index-only={sorted(set(index_map)-set(leaf_map))[:5]} "
            f"tree-only={sorted(set(leaf_map)-set(index_map))[:5]}",
        )

    surfaces: list[dict[str, Any]] = []
    unknowns: list[dict[str, str]] = []
    load_paths: list[dict[str, Any]] = []
    for path in sorted(index_map):
        idx = index_map[path]
        leaf = leaf_map[path]
        if idx["mode"] != leaf["mode"] or idx["oid"] != leaf["oid"]:
            raise kernel.Refusal("CMD-G0-EXACT-SET", f"index/tree identity mismatch: {path}")
        text = read_tracked_text(path, idx["mode"])
        classification = classify_path(path, idx["mode"], text)
        kind = file_kind(idx["mode"], leaf["object_type"])
        generator = infer_generator(text)
        generated = classification == "generated consequence"
        owner = infer_owner(path)
        row = {
            "path": path,
            "mode": idx["mode"],
            "object_type": leaf["object_type"],
            "object_digest": leaf["oid"],
            "kind": kind,
            "classification": classification,
            "semantic_owner": owner,
            "operational_owner": owner,
            "generated": generated,
            "generator": generator,
        }
        surfaces.append(row)
        paths = detect_load_path(path)
        if paths:
            load_paths.append({"path": path, "load_paths": paths})
        if classification == "unknown" or kind == "unknown":
            unknowns.append(
                {
                    "path": path,
                    "reason": "unclassified path or Git object mode",
                    "standing": "UNKNOWN",
                }
            )
        if generated and not generator:
            unknowns.append(
                {
                    "path": path,
                    "reason": "generated header does not name canonical source",
                    "standing": "UNKNOWN",
                }
            )

    untracked_raw = run_bytes("git", "ls-files", "--others", "--exclude-standard", "-z")
    untracked = sorted(
        item.decode("utf-8", "surrogateescape")
        for item in untracked_raw.split(b"\0")
        if item
    )
    tree_digest = kernel.digest(
        [
            {
                "path": item["path"],
                "mode": item["mode"],
                "type": item["object_type"],
                "oid": item["object_digest"],
            }
            for item in surfaces
        ]
    )
    repository = {
        "schema": "ggen.cmd.repository-observation.v1",
        **identity,
        "tree_digest": tree_digest,
        "tracked_object_count": len(surfaces),
        "directory_tree_count": len([row for row in tree if row["object_type"] == "tree"]),
        "untracked_count": len(untracked),
        "observation_time": now_iso(),
        "toolchain": {
            "git": run("git", "--version"),
            "python": sys.version.split()[0],
            "coordinator": COMPILER_IDENTITY,
        },
    }
    return {
        "repository": repository,
        "surfaces": surfaces,
        "load_paths": load_paths,
        "unknowns": unknowns,
        "untracked": untracked,
    }


