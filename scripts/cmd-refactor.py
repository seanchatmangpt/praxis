def gall_data() -> dict[str, Any]:
    g = graph()
    checkpoints: list[dict[str, Any]] = []
    for subject in sorted(
        g.subjects(RDF.type, CMD.Checkpoint),
        key=lambda item: int(one(g, item, CMD.checkpointOrder)),
    ):
        checkpoints.append(
            {
                "code": str(one(g, subject, CMD.checkpointCode)),
                "order": int(one(g, subject, CMD.checkpointOrder)),
                "dependencies": sorted(
                    str(one(g, dependency, CMD.checkpointCode))
                    for dependency in g.objects(subject, CMD.dependsOnCheckpoint)
                ),
                "allowed_paths": sorted(str(value) for value in g.objects(subject, CMD.allowedPath)),
                "forbidden_paths": sorted(str(value) for value in g.objects(subject, CMD.forbiddenPath)),
                "required_commands": sorted(str(value) for value in g.objects(subject, CMD.requiredCommand)),
                "required_artifacts": sorted(str(value) for value in g.objects(subject, CMD.requiredArtifact)),
                "required_refusals": sorted(str(value) for value in g.objects(subject, CMD.requiredRefusal)),
                "standing_ceiling": local_name(one(g, subject, CMD.standingCeiling)),
            }
        )
    return {
        "schema": "ggen.cmd.gall-checkpoints.v1",
        "checkpoints": checkpoints,
        "dependency_closed": all(
            all(dep in {row["code"] for row in checkpoints[:index]} for dep in row["dependencies"])
            for index, row in enumerate(checkpoints)
        ),
    }


