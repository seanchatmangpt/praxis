def graph() -> Graph:
    g = Graph()
    for path in GRAPH_FILES:
        g.parse(path, format="turtle")
    return g


def local_name(value: Any) -> str:
    text = str(value)
    return text.rsplit("#", 1)[-1].rsplit("/", 1)[-1]


def one(g: Graph, subject: URIRef, predicate: URIRef) -> Any:
    values = list(g.objects(subject, predicate))
    if len(values) != 1:
        raise kernel.Refusal(
            "CMD-G2-CARDINALITY",
            f"{subject} {predicate}: expected one, observed {len(values)}",
        )
    return values[0]


def semantic_data() -> dict[str, Any]:
    g = graph()
    try:
        from pyshacl import validate
    except ImportError as exc:
        raise kernel.Refusal("CMD-G2-SHACL-BLOCKED", "pyshacl is required") from exc
    shapes_graph = Graph()
    shapes_graph.parse(SHAPES, format="turtle")
    conforms, report_graph, report_text = validate(
        data_graph=g,
        shacl_graph=shapes_graph,
        inference="rdfs",
        abort_on_first=False,
        allow_infos=False,
        allow_warnings=False,
    )
    if not conforms:
        raise kernel.Refusal("CMD-G2-SHACL", report_text)
    ontology_digest = kernel.digest(
        {relative(path): digest_file(path) for path in (*GRAPH_FILES, SHAPES)}
    )
    return {
        "schema": "ggen.cmd.semantic-authority.v1",
        "ontology_digest": ontology_digest,
        "triple_count": len(g),
        "shacl_conforms": True,
        "report_digest": digest_bytes(report_graph.serialize(format="turtle").encode()),
        "controlled_standing": sorted(STANDING),
    }


