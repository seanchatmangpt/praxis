def safe_target(root: Path, relative_path: str) -> Path:
    if not relative_path or Path(relative_path).is_absolute():
        raise kernel.Refusal("CMD-G7-PATH-ESCAPE", relative_path)
    candidate = (root / relative_path).resolve(strict=False)
    root_resolved = root.resolve(strict=False)
    try:
        candidate.relative_to(root_resolved)
    except ValueError as exc:
        raise kernel.Refusal("CMD-G7-PATH-ESCAPE", relative_path) from exc
    parent = candidate.parent
    while parent != root_resolved.parent and parent != root_resolved:
        if parent.exists() and parent.is_symlink():
            raise kernel.Refusal("CMD-G7-SYMLINK-ESCAPE", str(parent))
        parent = parent.parent
    return candidate


