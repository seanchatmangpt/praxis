def dimensions_and_options() -> tuple[list[kernel.Dimension], list[kernel.Option]]:
    g = graph()
    dimensions: list[kernel.Dimension] = []
    options: list[kernel.Option] = []
    for subject in sorted(g.subjects(RDF.type, CMD.Dimension), key=str):
        dimensions.append(
            kernel.Dimension(
                identity=str(one(g, subject, CMD.identity)),
                domain=local_name(one(g, subject, CMD.domain)),
                order=int(one(g, subject, CMD.dimensionOrder)),
                cardinality=int(one(g, subject, CMD.selectionCardinality)),
                coverage_mode=local_name(one(g, subject, CMD.coverageMode)),
                risk_class=str(one(g, subject, CMD.riskClass)),
                resource_ceiling=int(one(g, subject, CMD.resourceCeiling)),
            )
        )
    for subject in sorted(g.subjects(RDF.type, CMD.Option), key=str):
        options.append(
            kernel.Option(
                identity=str(one(g, subject, CMD.identity)),
                dimension=str(one(g, one(g, subject, CMD.forDimension), CMD.identity)),
                implementation=str(one(g, subject, CMD.implementation)),
                resource_cost=int(one(g, subject, CMD.resourceCost)),
                authority_requirement=str(one(g, subject, CMD.authorityRequirement)),
                reversal_class=local_name(one(g, subject, CMD.reversalClass)),
                requires_options=tuple(
                    sorted(
                        str(one(g, option, CMD.identity))
                        for option in g.objects(subject, CMD.requiresOption)
                    )
                ),
                incompatible_with=tuple(
                    sorted(
                        str(one(g, option, CMD.identity))
                        for option in g.objects(subject, CMD.incompatibleWith)
                    )
                ),
                provides_capabilities=tuple(
                    sorted(local_name(value) for value in g.objects(subject, CMD.providesCapability))
                ),
                requires_capabilities=tuple(
                    sorted(local_name(value) for value in g.objects(subject, CMD.requiresCapability))
                ),
            )
        )
    kernel.dimension_map(dimensions)
    kernel.option_map(options, {item.identity: item for item in dimensions})
    return sorted(dimensions, key=lambda item: item.order), sorted(options, key=lambda item: item.identity)


def bounded_product(domain: str, dimensions: Sequence[kernel.Dimension], options: Sequence[kernel.Option]) -> tuple[list[kernel.Candidate], dict[str, Any]]:
    domain_dimensions = [item for item in dimensions if item.domain == domain]
    option_lists = [
        sorted(
            [item for item in options if item.dimension == dimension.identity],
            key=lambda item: item.identity,
        )
        for dimension in domain_dimensions
    ]
    raw_count = 1
    for items in option_lists:
        raw_count *= len(items)
    if raw_count > MAX_PRODUCT:
        raise kernel.Refusal(
            "CMD-G3-PRODUCT-OVERFLOW",
            f"domain={domain}, raw={raw_count}, ceiling={MAX_PRODUCT}",
        )
    valid: list[kernel.Candidate] = []
    refusal_counts: dict[str, int] = {}
    for combination in product(*option_lists):
        selected = {
            dimension.identity: option.identity
            for dimension, option in zip(domain_dimensions, combination, strict=True)
        }
        try:
            candidate = kernel.validate_candidate(domain, selected, dimensions, options)
        except kernel.Refusal as refusal:
            refusal_counts[refusal.code] = refusal_counts.get(refusal.code, 0) + 1
            continue
        valid.append(candidate)
    signatures = [item.signature for item in valid]
    if len(signatures) != len(set(signatures)):
        raise kernel.Refusal("CMD-G3-DUPLICATE-CANDIDATE", domain)
    coverage = kernel.verify_candidate_set(valid, declared_count=len(valid))
    return sorted(valid, key=lambda item: item.signature), {
        "domain": domain,
        "raw_product_count": raw_count,
        "valid_candidate_count": len(valid),
        "refused_candidate_count": raw_count - len(valid),
        "refusal_counts": dict(sorted(refusal_counts.items())),
        **coverage,
    }


