def verify_observation_data(
    repository: Mapping[str, Any], surfaces: Sequence[Mapping[str, Any]]
) -> None:
    current = observe_data()
    expected_rows = [
        (item["path"], item["mode"], item["object_type"], item["object_digest"])
        for item in surfaces
    ]
    actual_rows = [
        (item["path"], item["mode"], item["object_type"], item["object_digest"])
        for item in current["surfaces"]
    ]
    if expected_rows != actual_rows:
        raise kernel.Refusal("CMD-G0-EXACT-SET", "tracked path/mode/type/digest set changed")
    if repository.get("base_commit_sha") != current["repository"]["base_commit_sha"]:
        raise kernel.Refusal("CMD-G0-EXACT-SET", "resolved base commit changed")
    if repository.get("base_ref") != current["repository"]["base_ref"]:
        raise kernel.Refusal("CMD-G0-EXACT-SET", "resolved base ref changed")
    if repository.get("head_commit_sha") != current["repository"]["head_commit_sha"]:
        raise kernel.Refusal("CMD-G9-EXACT-HEAD", "head commit changed")
    if repository.get("head_tree_sha") != current["repository"]["head_tree_sha"]:
        raise kernel.Refusal("CMD-G0-EXACT-SET", "head tree changed")
    if repository.get("tree_digest") != current["repository"]["tree_digest"]:
        raise kernel.Refusal("CMD-G0-EXACT-SET", "tree digest changed")


